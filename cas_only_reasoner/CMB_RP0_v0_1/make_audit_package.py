def sha256(path):
    with open(path, "rb") as f:
        return hashlib.sha256(f.read()).hexdigest()


def git(*args):
    try:
        return subprocess.run(["git"] + list(args), cwd=ROOT, capture_output=True,
                              text=True, timeout=30).stdout.strip()
    except Exception as e:
        return f"<unavailable: {type(e).__name__}>"


def literals(path, names):
    """Read top-level assignments by parsing, not importing -- importing needs a GPU."""
    tree = ast.parse(open(path, encoding="utf-8").read())
    out = {}
    for node in tree.body:
        if isinstance(node, ast.Assign) and len(node.targets) == 1:
            t = node.targets[0]
            if isinstance(t, ast.Name) and t.id in names:
                try:
                    out[t.id] = repr(ast.literal_eval(node.value))
                except Exception:
                    out[t.id] = ast.unparse(node.value)
    return out


def source_of(path, funcname):
    tree = ast.parse(open(path, encoding="utf-8").read())
    for node in tree.body:
        if isinstance(node, ast.FunctionDef) and node.name == funcname:
            return ast.unparse(node)
    return f"<{funcname} not found>"


