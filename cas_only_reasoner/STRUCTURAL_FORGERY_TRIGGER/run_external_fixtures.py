"""Run EXTERNAL, SPEC-ONLY conformance fixtures against the structural-forgery trigger.

Exists to close GLM audit finding 1 on commit 2625337f:

    "The suite is the checker validating itself. Before any production binding, add an external
     negative corpus -- fixtures generated by someone other than the checker's author -- so the
     validator cannot share a blind spot with the code it tests."

`validate_trigger.py` was written by the same author as `check_structural_trigger.py`, so the
two can share an assumption and neither would notice. The fixtures this script runs were
authored from `STRUCTURAL_FORGERY_DEFENCE_TRIGGER.md` ALONE, by parties who never read the
implementation or the existing suite, and who PREDICTED the state and exit code before anything
was executed.

    python run_external_fixtures.py external_fixtures.json

EVERY DIVERGENCE IS A FINDING, and it is one of exactly three things:

    IMPLEMENTATION BUG   the code does not do what the spec says
    SPEC AMBIGUITY       the spec does not determine the answer, so the code chose
    FIXTURE ERROR        the author misread a spec sentence that is in fact unambiguous

The third is the only benign one, and it must be argued from the spec text -- never assumed
because the implementation disagreed. That inversion is how a self-validating suite goes blind.

Exit 0 if every fixture matches its prediction; 1 otherwise.
"""
import hashlib
import json
import os
import subprocess
import sys
import tempfile

HERE = os.path.dirname(os.path.abspath(__file__))
CHK = os.path.join(HERE, "check_structural_trigger.py")


def with_digest(man):
    """Fixture authors write config_digest 'AUTO'; compute the real one for them.

    An explicit value is left alone, because a deliberately wrong digest is a valid test.
    """
    if not isinstance(man, dict) or man.get("config_digest") != "AUTO":
        return man
    m = dict(man)
    m.pop("config_digest", None)
    body = {k: v for k, v in m.items() if not k.startswith("_")}
    m["config_digest"] = hashlib.sha256(
        json.dumps(body, sort_keys=True).encode()).hexdigest()
    return m


def run_one(fx):
    args_spec = fx.get("args") or {}
    with tempfile.TemporaryDirectory() as d:
        argv = [sys.executable, CHK]

        man = with_digest(fx.get("manifest"))
        mp = os.path.join(d, "manifest.json")
        if man is not None:
            with open(mp, "w", encoding="utf-8") as f:
                json.dump(man, f)
        argv += ["--manifest", mp]          # absent file is itself a documented case

        if fx.get("corpus") is not None:
            cp = os.path.join(d, "corpus.json")
            with open(cp, "w", encoding="utf-8") as f:
                json.dump(fx["corpus"], f)
            argv += ["--corpus", cp]
        if args_spec.get("expected_scope"):
            argv += ["--expected-scope", args_spec["expected_scope"]]
        if args_spec.get("job_id"):
            argv += ["--job-id", args_spec["job_id"]]
        if args_spec.get("pipeline_config") is not None:
            pp = os.path.join(d, "pipeline.json")
            with open(pp, "w", encoding="utf-8") as f:
                json.dump(args_spec["pipeline_config"], f)
            argv += ["--pipeline-config", pp]
        if args_spec.get("watch_ack") is not None:
            ap = os.path.join(d, "ack.json")
            with open(ap, "w", encoding="utf-8") as f:
                json.dump(args_spec["watch_ack"], f)
            argv += ["--watch-ack", ap]

        r = subprocess.run(argv, capture_output=True, text=True)
        line = [l for l in r.stdout.splitlines() if l.startswith("TRIGGER STATE:")]
        state = line[0].split()[2] if line else "NO_STATE"
        return state, r.returncode, r.stdout


def main():
    path = sys.argv[1] if len(sys.argv) > 1 else os.path.join(HERE, "external_fixtures.json")
    with open(path, encoding="utf-8") as f:
        blob = json.load(f)
    fixtures = blob["fixtures"] if isinstance(blob, dict) else blob

    print(f"EXTERNAL SPEC-ONLY CONFORMANCE -- {len(fixtures)} fixtures from {path}")
    print("Authored from the specification alone, by parties who never read the implementation.")
    print()
    hdr = f"{'#':>3}  {'surface':<20}{'fixture':<44}{'predicted':>20}{'actual':>20}{'rc':>4}"
    print(hdr)
    print("-" * len(hdr))

    diverged, ambiguous = [], []
    for i, fx in enumerate(fixtures, 1):
        state, rc, out = run_one(fx)
        want, want_rc = fx["predicted_state"], fx["predicted_exit"]
        ok = (state == want and rc == want_rc)
        if not ok:
            diverged.append((i, fx, state, rc, out))
        if not fx.get("spec_determines", True):
            ambiguous.append((i, fx, state, rc))
        mark = "ok" if ok else "<-- DIVERGES"
        amb = "" if fx.get("spec_determines", True) else "  (spec ambiguous)"
        print(f"{i:>3}  {fx.get('surface', '?'):<20}{fx['name'][:43]:<44}"
              f"{want + '/' + str(want_rc):>20}{state + '/' + str(rc):>20}{rc:>4}  {mark}{amb}")

    print()
    print(f"MATCHED   {len(fixtures) - len(diverged)} / {len(fixtures)}")
    print(f"DIVERGED  {len(diverged)}")
    print(f"flagged by their author as SPEC-AMBIGUOUS: {len(ambiguous)}")

    if diverged:
        print()
        print("=" * 100)
        print("DIVERGENCES -- each is an implementation bug, a spec ambiguity, or a fixture")
        print("error. Argue which from the SPEC TEXT, never from what the implementation did.")
        print("=" * 100)
        for i, fx, state, rc, out in diverged:
            print()
            print(f"[{i}] {fx['name']}   surface={fx.get('surface')}")
            print(f"    predicted : {fx['predicted_state']} / exit {fx['predicted_exit']}")
            print(f"    actual    : {state} / exit {rc}")
            print(f"    spec_determines: {fx.get('spec_determines')}")
            print(f"    author's rationale: {fx.get('rationale', '')[:400]}")
            reasons = [l.strip() for l in out.splitlines()
                       if l.strip().startswith("- ")][:6]
            if reasons:
                print("    checker said:")
                for rr in reasons:
                    print(f"      {rr}")

    if ambiguous:
        print()
        print("SPEC AMBIGUITIES flagged by the fixture authors (worth fixing in the doc even")
        print("where the implementation happened to agree):")
        for i, fx, state, rc in ambiguous:
            print(f"  [{i}] {fx['name']} -- author guessed {fx['predicted_state']}, "
                  f"actual {state}")
            print(f"        {fx.get('rationale', '')[:300]}")

    return 1 if diverged else 0


if __name__ == "__main__":
    sys.exit(main())
