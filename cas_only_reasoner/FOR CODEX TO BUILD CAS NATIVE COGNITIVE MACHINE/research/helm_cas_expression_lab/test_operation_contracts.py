"""Q2 tests -- the contract is only a contract if a program checks it.

Four things are asserted, and each is a different kind of claim:

  1. PINS HOLD. Every source file the contract names still hashes to what the contract recorded.
     A moved or edited engine file fails here before any semantics are trusted.
  2. THE REFERENCE MATCHES THE HAND-PINNED CASES. `reference_ops.py` is checked against expected
     outputs that were written from the Rust source by reading it, not generated by the reference.
  3. THE ALGEBRA IS WHAT THE CONTRACT SAYS. Exhaustive where the domain is small enough: all 10
     involutions, all 100 compositions (identity, commutativity), all 1,000 associativity triples,
     all 16,000 admissibility triples against a second, independently written predicate, all 1,600
     mask cells against the block rule, the section law on a grid, and the retraction failure.
  4. THE REFERENCE IS NOT IMPORTED BY A LEARNER. Directive D04. Any file whose name starts with
     `learner` under this lab may not import `reference_ops`.

Run:  python -m pytest research/helm_cas_expression_lab/test_operation_contracts.py -q
"""
import hashlib
import json
import math
import pathlib
import re
import sys

import pytest

HERE = pathlib.Path(__file__).resolve().parent
REPO = HERE.parents[3]
sys.path.insert(0, str(HERE))
import reference_ops as ref  # noqa: E402

CONTRACT_PATH = HERE / "OPERATION_CONTRACTS.json"
CONTRACT = json.loads(CONTRACT_PATH.read_text(encoding="utf-8"))
OPS = CONTRACT["operations"]


def _lf(path):
    return path.read_bytes().replace(b"\r\n", b"\n")     # the contract hash policy: LF-normalised



def _sha(path):
    return hashlib.sha256(_lf(REPO / path)).hexdigest()


# --- 1. pins -----------------------------------------------------------------------------------
def test_every_pinned_source_still_matches():
    pins = [op["pinned_implementation"] for op in OPS.values()]
    pins += [op["corroborating_implementation"] for op in OPS.values() if "corroborating_implementation" in op]
    pins += [CONTRACT["coordinates"]["tokenizer_pin"]]
    manifest = json.loads((HERE / "pinned_sources" / "PINNED_SOURCES.json").read_text(encoding="utf-8"))
    recorded = {row["origin"]: row["sha256"] for row in manifest["files"]}
    for p in pins:
        vendored = HERE / p["vendored_path"]
        assert vendored.is_file(), "VENDORED_MISSING:%s" % p["path"]
        assert hashlib.sha256(_lf(vendored)).hexdigest() == p["sha256"] == recorded[p["path"]], "VENDORED_DIVERGED:%s" % p["path"]
        assert len(_lf(vendored)) == p["bytes"], "PIN_SIZE:%s" % p["path"]
        origin = REPO / p["path"]
        if origin.is_file():                 # drift detection whenever the origin is checked out
            assert _sha(p["path"]) == p["sha256"], "ORIGIN_DIVERGED_FROM_PIN:%s" % p["path"]
    ref_pin = CONTRACT["reference_module"]
    assert _sha(ref_pin["path"]) == ref_pin["sha256"], "REFERENCE_MODULE_EDITED_AFTER_CONTRACT"


def test_contract_digest_is_of_its_own_body():
    body = {k: v for k, v in CONTRACT.items() if k != "contract_digest"}
    assert hashlib.sha256(json.dumps(body, indent=1, sort_keys=True).encode("utf-8")).hexdigest() == CONTRACT["contract_digest"]


# --- 2. hand-pinned cases ----------------------------------------------------------------------
def test_involute_cases():
    for case in OPS["involute"]["expected_cases"]:
        assert ref.involute(*case["in"]) == case["out"]
    for bad in OPS["involute"]["invalid_cases"]:
        with pytest.raises(ref.InvalidInput):
            ref.involute(*bad)


def test_compose_cases():
    for case in OPS["compose"]["expected_cases"]:
        assert ref.compose(*case["in"]) == case["out"]
    for bad in OPS["compose"]["invalid_cases"]:
        with pytest.raises(ref.InvalidInput):
            ref.compose(*bad)


def test_is_admissible_cases():
    for case in OPS["is_admissible"]["expected_cases"]:
        op, s, t = case["in"]
        assert ref.is_admissible(op, tuple(s), tuple(t)) is case["out"], case
    for bad in OPS["is_admissible"]["invalid_cases"]:
        op, s, t = bad
        with pytest.raises(ref.InvalidInput):
            ref.is_admissible(op, tuple(s) if isinstance(s, list) else s, tuple(t) if isinstance(t, list) else t)


def test_domain_descent_cases():
    for case in OPS["domain_descent_mask"]["expected_cases"]:
        s, t = case["in"]
        assert ref.may_attend(tuple(s), tuple(t)) is case["out"], case


def test_rpm_cases():
    for case in OPS["rpm_embed_realize"]["expected_cases"]:
        e = ref.rpm_embed(*case["in"])
        assert all(abs(a - b) <= ref.RMS_LAW_TOLERANCE for a, b in zip(e, case["embed"])), case
        assert ref.rpm_realize(e) == case["realize"]
    for bad in OPS["rpm_embed_realize"]["invalid_cases"]:
        value = float("nan") if bad == ["nan"] else bad[0]
        with pytest.raises(ref.InvalidInput):
            ref.rpm_embed(value)
    for case in OPS["rpm_embed_realize"]["retraction_failure_cases"]:
        assert ref.rpm_retraction_law_fails_for(tuple(case["embedded"])), case


# --- 3. the algebra, exhaustively ----------------------------------------------------------------
def test_involute_is_self_inverse_with_exactly_four_fixed_points():
    assert all(ref.involute(ref.involute(n)) == n for n in range(10))
    assert {n for n in range(10) if ref.involute(n) == n} == set(ref.SELF_DUAL) == {0, 1, 4, 7}


def test_compose_identity_commutative_associative_and_a_group():
    assert all(ref.compose(0, k) == k and ref.compose(k, 0) == k for k in range(10))
    assert all(ref.compose(a, b) == ref.compose(b, a) for a in range(10) for b in range(10))
    assert all(ref.compose(ref.compose(a, b), c) == ref.compose(a, ref.compose(b, c))
               for a in range(10) for b in range(10) for c in range(10))
    assert all(ref.compose(k, (10 - k) % 10) == 0 for k in range(10))


def _admissible_second_opinion(op, source, target):
    """Written independently of reference_ops, straight from operators.rs:110-125, as a sanity check."""
    if op == 0:
        return source == target
    return source[0] == target[0] or target[1] == op


def test_is_admissible_all_16000_triples_agree_with_a_second_reading_of_the_source():
    states = [(d, n) for d in ref.DOMAINS for n in range(10)]
    counts = {}
    for op in range(10):
        n_true = 0
        for s in states:
            for t in states:
                got = ref.is_admissible(op, s, t)
                assert got is _admissible_second_opinion(op, s, t), (op, s, t)
                n_true += got
        counts[op] = n_true
    # CO-0: the diagonal only. CO-k: 4 domains x 100 intra pairs + cross-domain pairs with target noetic k:
    # 40 sources x 3 other domains x 1 target each = 120. Total 400 + 120 = 520.
    assert counts[0] == 40 and all(counts[k] == 520 for k in range(1, 10)), counts


def test_is_admissible_is_not_symmetric():
    asym = sum(1 for op in range(1, 10) for s in [(d, n) for d in ref.DOMAINS for n in range(10)]
               for t in [(d, n) for d in ref.DOMAINS for n in range(10)]
               if ref.is_admissible(op, s, t) != ref.is_admissible(op, t, s))
    assert asym > 0


def test_domain_descent_mask_blocks_and_count():
    m = ref.domain_descent_mask()
    assert len(m) == 40 and all(len(r) == 40 for r in m)
    assert sum(sum(r) for r in m) == 1000
    for row in range(40):
        for col in range(40):
            assert m[row][col] is ((col // 10) <= (row // 10)), (row, col)
    assert all(m[i][i] for i in range(40))


def test_rpm_section_law_on_a_grid_and_retraction_fails():
    for k in range(0, 1001):
        s = k / 1000.0
        assert ref.rpm_section_law_holds(s), s
    assert ref.rpm_retraction_law_fails_for((0.5, 0.9, 0.1))
    assert not ref.rpm_retraction_law_fails_for(ref.rpm_embed(0.36))   # a genuine image of eta round-trips
    assert math.isnan(float("nan"))


# --- coordinates ---------------------------------------------------------------------------------
def test_coordinate_map_round_trips_all_40_and_matches_the_frozen_tokenizer():
    # the origin is sparse-excluded in this worktree; the contract pins the vendored byte copy
    tok = json.loads((HERE / CONTRACT["coordinates"]["tokenizer_pin"]["vendored_path"]).read_text(encoding="utf-8"))["token_to_id"]
    m = CONTRACT["coordinates"]["explicit_map_engine_index_to_tokenizer_id"]
    assert len(m) == 40 and len(set(m.values())) == 40
    for d in ref.DOMAINS:
        for n in range(10):
            idx = ref.state_index(d, n)
            assert ref.state_from_index(idx) == (d, n)
            assert m[str(idx)] == ref.tokenizer_id(d, n) == tok["^%d^%s" % (n, d)]


# --- 4. reference / learner separation -------------------------------------------------------------
def test_no_learner_file_imports_the_reference():
    offenders = []
    for path in HERE.rglob("learner*.py"):
        if re.search(r"^\s*(from|import)\s+reference_ops\b", path.read_text(encoding="utf-8"), re.M):
            offenders.append(path.name)
    assert not offenders, "REFERENCE_LEAKED_INTO_LEARNER:%s" % offenders
