class Material:
    def __init__(self, force=False, quiet=False):
        from cas_meta2.typed_teaching import practice_contract as c, checker, answers, slots
        import evaluate_gates as eg
        self.c, self.checker, self.answers, self.slots, self.eg = c, checker, answers, slots, eg
        self.canonical = slots.canonical
        t0 = time.monotonic()
