"""Shared read-only material loader and private-answer cache for the leaks-lens scripts.

Building the private admissible-answer set for all 564 records is the expensive step
(the analogy and correspondence rules enumerate permutations of every bank world). This
module computes it once and caches it beside the scripts, then every other lk script
starts from the cache. The cache is generated BY the real functions
(checker.derive_target and evaluate_gates.eligible_questions), keyed to the checker
profile digest, and spot-checked against a fresh derivation on every load.

Pure Python, no torch, no network, read-only on every existing file. Run directly to
build/verify the cache and print the material facts.

    python lk0_material.py [--force]
"""
