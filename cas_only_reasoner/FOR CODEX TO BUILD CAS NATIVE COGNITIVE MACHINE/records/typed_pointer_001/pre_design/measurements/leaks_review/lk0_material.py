        self.held_set, self.trained_set, self.excluded_set = set(self.held), set(self.trained), set(self.excluded)
        self.packets = self._packets()
        t2 = time.monotonic()
        self.worlds = {w["world_id"]: w for w in self.frozen["bank"]["worlds"]}
        self.by_id = {r["record_id"]: r for r in self.frozen["registry"]}
        self.side = {**{k: "held" for k in self.held}, **{k: "trained" for k in self.trained},
                     **{k: "excluded" for k in self.excluded}}
        self.kind_of = {r["query"]["query_id"]: r["query"]["kind"] for r in self.frozen["registry"]}
        self.world_of = {r["query"]["query_id"]: r["source_world_id"] for r in self.frozen["registry"]}
        self.held_questions = c.held_back_questions(self.frozen)
        self.trained_questions = {}
