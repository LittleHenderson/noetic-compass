"""Generate the exact MATERIAL pins for the 18 practice checkpoints the pointer study ships.

The pointer contract must carry these as constants so the launch-time `git_package_bytes`
check admits the checkpoint files (they are under `records/`, which its scope otherwise
rejects: pipeline review RK5, `PRACTICE_SOURCE_MEMBER_SCOPE`).

MATERIAL rows are keyed by a path RELATIVE TO THE CNCM ROOT and carry exactly
`{"bytes": int, "sha256": str}` (worker_contract.py:26-29, INTERFACE_SPEC_SHARED G.2).

Pure Python, standard library only. $0. Reads only; writes one JSON beside itself.

Run from a short working directory (the deep OneDrive path can break process start):
    python -B <path to this file>
"""
import hashlib
import json
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
CNCM = (HERE.parents[3] / "..").resolve()  # records/typed_pointer_001/pre_design/contract_pins -> CNCM
# Resolve CNCM explicitly rather than by parent arithmetic guesswork.
CNCM = Path(r"C:\Users\wakil\OneDrive\Desktop\tksCAS\cas_only_reasoner\FOR CODEX TO BUILD "
            r"CAS NATIVE COGNITIVE MACHINE\_worktrees\vision-next\cas_only_reasoner\FOR CODEX "
            r"TO BUILD CAS NATIVE COGNITIVE MACHINE")

SEEDS = (20260917, 20260918, 20260919)
STAGES = ("initial", "pass_01", "final")
BASE = "records/typed_practice_001/receipt_%d/checkpoints/%s"

material = {}
run_identity_digest = {}
model_state_identity = {}
sidecar_sha_agrees = {}

for seed in SEEDS:
    for stage in STAGES:
        pt_rel = (BASE % (seed, stage)) + ".pt"
        js_rel = (BASE % (seed, stage)) + "_checkpoint.json"
        pt = CNCM / pt_rel
        js = CNCM / js_rel
        assert pt.is_file(), "MISSING " + str(pt)
        assert js.is_file(), "MISSING " + str(js)

        raw = pt.read_bytes()
        digest = hashlib.sha256(raw).hexdigest()
        material[pt_rel] = {"bytes": len(raw), "sha256": digest}
        material[js_rel] = {"bytes": js.stat().st_size,
                            "sha256": hashlib.sha256(js.read_bytes()).hexdigest()}

        recorded = json.loads(js.read_text(encoding="utf-8"))
        sidecar_sha_agrees[pt_rel] = (recorded.get("sha256") == digest)
        run_identity_digest[pt_rel] = recorded.get("run_identity_digest")
        model_state_identity[pt_rel] = (recorded.get("metadata") or {}).get("model_state_identity")

out = {
    "note": ("Generated by make_pins.py. MATERIAL keys are CNCM-root-relative and carry exactly "
             "bytes + sha256. The launcher's git_package_bytes admits these paths only if the new "
             "pointer contract lists them in MATERIAL (pipeline review RK5)."),
    "seeds": list(SEEDS),
    "stages": list(STAGES),
    "material": dict(sorted(material.items())),
    "run_identity_digest": dict(sorted(run_identity_digest.items())),
    "model_state_identity": dict(sorted(model_state_identity.items())),
    "sidecar_sha256_agrees_with_file": dict(sorted(sidecar_sha_agrees.items())),
    "totals": {
        "files": len(material),
        "bytes": sum(row["bytes"] for row in material.values()),
        "pt_files": len(run_identity_digest),
        "pt_bytes": sum(material[k]["bytes"] for k in run_identity_digest),
        "json_files": len(material) - len(run_identity_digest),
    },
}

(HERE / "checkpoint_pins.json").write_bytes(
    (json.dumps(out, indent=1, sort_keys=True) + "\n").encode("utf-8"))

# Report, so the numbers are visible in the run log.
print(json.dumps(out["totals"], sort_keys=True))
print("all sidecar sha256 agree:", all(sidecar_sha_agrees.values()))
for key in sorted(run_identity_digest):
    print("%-72s %8d  %s  rid=%s" % (key, material[key]["bytes"], material[key]["sha256"][:16],
                                    str(run_identity_digest[key])[:16]))
print("distinct run_identity_digest values:", len(set(run_identity_digest.values())))
print("distinct model_state_identity values:", len(set(model_state_identity.values())))
