"""BrokerOrderRequest and OrderOutcome schemas."""

from datetime import datetime
from enum import Enum
from typing import Optional

from pydantic import BaseModel, Field, field_validator, model_validator

from cas_forex.instruments import broker_symbol
from cas_forex.schemas.forecast import SUPPORTED_SYMBOLS, Direction
from cas_forex.time_utils import utc_now


class OrderType(str, Enum):
    MARKET = "MARKET"
    LIMIT = "LIMIT"
    STOP = "STOP"


class OrderStatus(str, Enum):
    PENDING = "PENDING"
    EXECUTED = "EXECUTED"
    REJECTED = "REJECTED"
    CANCELLED = "CANCELLED"
    PARTIAL = "PARTIAL"


class BrokerMode(str, Enum):
    SIMULATED = "SIMULATED"
    PAPER_MT5 = "PAPER_MT5"
    PAPER_MT4 = "PAPER_MT4"
    LIVE_MT5 = "LIVE_MT5"
    LIVE_MT4 = "LIVE_MT4"


class BrokerHealthState(str, Enum):
    CONNECTED = "CONNECTED"
    DISCONNECTED = "DISCONNECTED"
    MARGIN_ERROR = "MARGIN_ERROR"
    EXECUTION_MISMATCH = "EXECUTION_MISMATCH"
    STALE_HEARTBEAT = "STALE_HEARTBEAT"
    LOCKED = "LOCKED"


class BrokerLockReason(str, Enum):
    BROKER_DISCONNECT_OPEN_TRADE = "BROKER_DISCONNECT_OPEN_TRADE"
    MARGIN_REJECT = "MARGIN_REJECT"
    FILL_PRICE_MISMATCH = "FILL_PRICE_MISMATCH"
    SYMBOL_MISMATCH = "SYMBOL_MISMATCH"
    VOLUME_MISMATCH = "VOLUME_MISMATCH"
    ORDER_STATE_MISMATCH = "ORDER_STATE_MISMATCH"


class BrokerOrderRequest(BaseModel):
    """A MetaTrader-ready order created after CAS Verifier ACCEPT.

    This is the output contract the MT5 bridge consumes. It must contain
    everything MetaTrader needs to place the order.
    """

    order_id: str = Field(
        ...,
        description="Unique order identifier generated by CAS Forex.",
    )
    decision_ref: str = Field(
        ...,
        description="Reference to the CASDecision that authorized this order.",
    )
    symbol: str = Field(..., description="Forex pair symbol.")
    order_type: OrderType = Field(
        default=OrderType.MARKET,
        description="MARKET, LIMIT, or STOP.",
    )
    direction: Direction = Field(..., description="LONG (BUY) or SHORT (SELL).")
    volume: float = Field(
        ...,
        description="Position size in standard lots.",
        gt=0,
    )
    price: float = Field(
        default=0.0,
        description="Requested price. 0.0 = market price.",
        ge=0,
    )
    stop_loss: float = Field(
        ...,
        description="Stop-loss price.",
        gt=0,
    )
    take_profit: float = Field(
        ...,
        description="Take-profit price.",
        gt=0,
    )
    comment: str = Field(
        default="CAS_FOREX_AUTO",
        description="Order comment visible in MetaTrader.",
        max_length=27,
    )
    magic_number: int = Field(
        default=20260601,
        description="Magic number to identify CAS Forex orders in MT5.",
    )
    slippage: int = Field(
        default=30,
        description="Maximum allowed slippage in points.",
        ge=0,
    )
    created_at: datetime = Field(
        default_factory=utc_now,
        description="UTC timestamp when this order was created.",
    )
    expiry_minutes: int = Field(
        default=5,
        description="Order expiry in minutes (for LIMIT/STOP orders).",
        ge=1,
    )

    @field_validator("symbol")
    @classmethod
    def symbol_must_be_supported(cls, v: str) -> str:
        if v not in SUPPORTED_SYMBOLS:
            raise ValueError(
                f"Unsupported symbol '{v}'. Supported: {sorted(SUPPORTED_SYMBOLS)}"
            )
        return v

    @model_validator(mode="after")
    def validate_order_geometry(self):
        """Guard broker-order SL/TP consistency with direction."""
        if self.order_type in (OrderType.LIMIT, OrderType.STOP) and self.price <= 0:
            raise ValueError(
                f"{self.order_type.value} order requires explicit price > 0"
            )

        if self.direction == Direction.LONG:
            # With price known: SL < price < TP
            if self.price > 0:
                if self.stop_loss >= self.price:
                    raise ValueError(
                        f"LONG order stop_loss ({self.stop_loss}) must be < price ({self.price})"
                    )
                if self.take_profit <= self.price:
                    raise ValueError(
                        f"LONG order take_profit ({self.take_profit}) must be > price ({self.price})"
                    )
            # Market order (price=0): at minimum SL < TP
            elif self.stop_loss >= self.take_profit:
                raise ValueError(
                    f"LONG market order: stop_loss ({self.stop_loss}) must be < take_profit ({self.take_profit})"
                )
        else:  # SHORT
            if self.price > 0:
                if self.stop_loss <= self.price:
                    raise ValueError(
                        f"SHORT order stop_loss ({self.stop_loss}) must be > price ({self.price})"
                    )
                if self.take_profit >= self.price:
                    raise ValueError(
                        f"SHORT order take_profit ({self.take_profit}) must be < price ({self.price})"
                    )
            elif self.stop_loss <= self.take_profit:
                raise ValueError(
                    f"SHORT market order: stop_loss ({self.stop_loss}) must be > take_profit ({self.take_profit})"
                )
        return self

    def to_mt5_request(self) -> dict:
        """Convert to MetaTrader 5 order request dictionary."""
        from cas_forex.schemas.forecast import Direction as Dir

        mt5_order_type = {
            (OrderType.MARKET, Dir.LONG): "ORDER_TYPE_BUY",
            (OrderType.MARKET, Dir.SHORT): "ORDER_TYPE_SELL",
            (OrderType.LIMIT, Dir.LONG): "ORDER_TYPE_BUY_LIMIT",
            (OrderType.LIMIT, Dir.SHORT): "ORDER_TYPE_SELL_LIMIT",
            (OrderType.STOP, Dir.LONG): "ORDER_TYPE_BUY_STOP",
            (OrderType.STOP, Dir.SHORT): "ORDER_TYPE_SELL_STOP",
        }.get((self.order_type, self.direction), "ORDER_TYPE_BUY")

        return {
            "symbol": broker_symbol(self.symbol),
            "order_type": mt5_order_type,
            "volume": self.volume,
            "price": self.price if self.price > 0 else None,
            "sl": self.stop_loss,
            "tp": self.take_profit,
            "deviation": self.slippage,
            "magic": self.magic_number,
            "comment": self.comment,
        }


class OrderOutcome(BaseModel):
    """Result of a broker order execution."""

    order_ref: str = Field(
        ...,
        description="Reference to BrokerOrderRequest.order_id.",
    )
    broker_ticket: Optional[int] = Field(
        default=None,
        description="Broker-assigned ticket number if executed.",
    )
    status: OrderStatus = Field(
        default=OrderStatus.PENDING,
        description="Execution status.",
    )
    filled_price: Optional[float] = Field(
        default=None,
        description="Actual fill price.",
    )
    slippage_pips: Optional[float] = Field(
        default=None,
        description="Realized slippage in pips.",
    )
    commission: Optional[float] = Field(
        default=None,
        description="Broker commission charged.",
    )
    swap: Optional[float] = Field(
        default=None,
        description="Swap/overnight fee charged.",
    )
    timestamp: datetime = Field(
        default_factory=utc_now,
        description="UTC timestamp of this outcome.",
    )
    error_message: Optional[str] = Field(
        default=None,
        description="Error message if REJECTED or CANCELLED.",
    )
    is_duplicate: bool = Field(
        default=False,
        description="Whether this order was detected as a duplicate.",
    )
    is_abnormal_slippage: bool = Field(
        default=False,
        description="Whether realized slippage exceeded acceptable bounds.",
    )
    broker_mode: BrokerMode = Field(
        default=BrokerMode.SIMULATED,
        description="Broker execution mode for this outcome.",
    )
    is_real_broker: bool = Field(
        default=False,
        description="True when an actual MetaTrader terminal executed or rejected the order.",
    )
    terminal_name: Optional[str] = Field(default=None)
    account_id_hash: Optional[str] = Field(default=None)
    server: Optional[str] = Field(default=None)
    raw_request_hash: Optional[str] = Field(default=None)
    raw_response_hash: Optional[str] = Field(default=None)
    lock_reason: Optional[BrokerLockReason] = Field(default=None)
