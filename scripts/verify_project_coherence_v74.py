#!/usr/bin/env python3
"""Verify the source-bound TKS v7.4 Gate 1 inventory and corrigendum."""

from __future__ import annotations

import hashlib
import json
import math
import re
from collections import Counter
from pathlib import Path

from pypdf import PdfReader


ROOT = Path(__file__).resolve().parents[1]
LANE = ROOT / "docs" / "working" / "project_coherence" / "gate1" / "v74"
INVENTORY_PATH = LANE / "TKS_V74_SURFACE_INVENTORY_v0.1.json"
CORRIGENDUM_PATH = LANE / "TKS_V74_CORRIGENDUM_v0.1.json"


def sha256_bytes(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest().upper()


def sha256_file(path: Path) -> str:
    return sha256_bytes(path.read_bytes())


def normalized(value: str) -> str:
    return re.sub(r"\s+", " ", value).strip().casefold()


def pdf_normalized(value: str) -> str:
    """Normalize PDF extraction while retaining punctuation as an anchor guard."""
    value = value.replace("\u00ad", "")
    value = re.sub(r"(?<=\w)-\s*\n\s*(?=\w)", "", value)
    return re.sub(r"\s+", "", value).casefold()


def matmul(a: list[list[float]], b: list[list[float]]) -> list[list[float]]:
    return [
        [sum(a[i][k] * b[k][j] for k in range(len(b))) for j in range(len(b[0]))]
        for i in range(len(a))
    ]


def transpose(a: list[list[float]]) -> list[list[float]]:
    return [list(row) for row in zip(*a)]


def matvec(a: list[list[float]], x: list[float]) -> list[float]:
    return [sum(v * w for v, w in zip(row, x)) for row in a]


def assert_close(actual: float, expected: float, label: str) -> None:
    if not math.isclose(actual, expected, rel_tol=1e-12, abs_tol=1e-12):
        raise AssertionError(f"{label}: expected {expected}, got {actual}")


def verify_fixtures() -> None:
    # Standard-basis lift of the two-state constant map.
    a = [[1.0, 1.0], [0.0, 0.0]]
    ata = matmul(transpose(a), a)
    if matmul(a, a) != a:
        raise AssertionError("two-state constant lift is expected to be idempotent")
    if matmul(ata, ata) == ata:
        raise AssertionError("A* A unexpectedly became a projection")
    assert_close(sum(ata[i][i] for i in range(2)), 2.0, "trace(A* A)")
    assert_close(math.sqrt(2.0), math.sqrt(max((2.0, 0.0))), "constant-lift norm")
    if transpose(a) == a:
        raise AssertionError("constant lift unexpectedly self-adjoint")

    # A two-cycle has no fixed point and never has a constant tail.
    swap = (1, 0)
    if any(swap[i] == i for i in range(2)):
        raise AssertionError("swap unexpectedly has a fixed point")
    orbit = [0]
    for _ in range(5):
        orbit.append(swap[orbit[-1]])
    if orbit != [0, 1, 0, 1, 0, 1]:
        raise AssertionError(f"unexpected two-cycle orbit: {orbit}")

    # The semigroup generated by identity and swap consists only of permutations.
    identity = (0, 1)

    def compose(f: tuple[int, ...], g: tuple[int, ...]) -> tuple[int, ...]:
        return tuple(f[g[i]] for i in range(len(g)))

    generated = {identity, swap}
    for _ in range(4):
        generated |= {compose(f, g) for f in generated for g in generated}
    if generated != {identity, swap} or any(len(set(f)) != 2 for f in generated):
        raise AssertionError("permutation counterexample semigroup is incorrect")

    # Prefix IFSs expand after adding the second constant generator.
    carrier = {0, 1}
    const0 = (0, 0)
    const1 = (1, 1)

    def hutchinson(maps: tuple[tuple[int, ...], ...], subset: set[int]) -> set[int]:
        return {f[x] for f in maps for x in subset}

    if hutchinson((const0,), carrier) != {0}:
        raise AssertionError("constant-0 prefix attractor fixture failed")
    if hutchinson((const0, const1), carrier) != {0, 1}:
        raise AssertionError("two-constant full attractor fixture failed")

    # The constant-map Markov difference is not negative semidefinite and lacks
    # the asserted orthogonality.
    delta = [[0.0, 0.0], [1.0, -1.0]]
    x = [2.0, 1.0]
    q = sum(xi * yi for xi, yi in zip(x, matvec(delta, x)))
    assert_close(q, 1.0, "constant-map Laplacian quadratic form")
    eig_zero = [1.0, 1.0]
    eig_minus_one = [0.0, 1.0]
    if sum(u * v for u, v in zip(eig_zero, eig_minus_one)) == 0:
        raise AssertionError("counterexample eigenvectors unexpectedly orthogonal")

    # A fixed point of the average pullback need not be fixed by each pullback.
    f = (0, 0, 2)
    g = (0, 2, 2)
    h = [0.0, 1.0, 2.0]
    pfh = [h[f[i]] for i in range(3)]
    pgh = [h[g[i]] for i in range(3)]
    average = [(u + v) / 2.0 for u, v in zip(pfh, pgh)]
    if average != h or pfh == h or pgh == h:
        raise AssertionError("average-invariance fixture failed")

    # Alternating a nonidentity involution and its inverse yields period-two
    # partial products, not convergence.
    partial = identity
    partials = []
    for _ in range(6):
        partial = compose(swap, partial)
        partials.append(partial)
    if partials != [swap, identity, swap, identity, swap, identity]:
        raise AssertionError("alternating-inverse fixture failed")

    # Every total map on up to four nonempty states has a functional-graph cycle,
    # the finite fact used in the radius-one correction.
    def has_cycle(mapping: tuple[int, ...]) -> bool:
        for start in range(len(mapping)):
            seen: set[int] = set()
            value = start
            while value not in seen:
                seen.add(value)
                value = mapping[value]
            if value in seen:
                return True
        return False

    import itertools

    for n in range(1, 5):
        for mapping in itertools.product(range(n), repeat=n):
            if not has_cycle(mapping):
                raise AssertionError(f"total map without a cycle: {mapping}")


def main() -> None:
    inventory = json.loads(INVENTORY_PATH.read_text(encoding="utf-8"))
    corrigendum = json.loads(CORRIGENDUM_PATH.read_text(encoding="utf-8"))

    source_by_id: dict[str, dict[str, object]] = {}
    for source in inventory["authority_sources"]:
        source_id = source["source_id"]
        if source_id in source_by_id:
            raise AssertionError(f"duplicate source id: {source_id}")
        source_by_id[source_id] = source
        path = Path(source["path"])
        if not path.is_file():
            raise AssertionError(f"missing authority source: {path}")
        actual_hash = sha256_file(path)
        if actual_hash != source["sha256"]:
            raise AssertionError(
                f"authority hash mismatch for {source_id}: {actual_hash} != {source['sha256']}"
            )
        if path.suffix.casefold() == ".pdf":
            actual_pages = len(PdfReader(str(path)).pages)
            if actual_pages != source["pages"]:
                raise AssertionError(
                    f"page-count mismatch for {source_id}: {actual_pages} != {source['pages']}"
                )

    master_path = Path(source_by_id["SRC-TKS74-MASTER-TEX"]["path"])
    master_dir = master_path.parent
    input_context = inventory["master_input_context"]["inputs"]
    for item in input_context:
        path = master_dir / f"{item['name']}.tex"
        if not path.is_file():
            raise AssertionError(f"missing master input context: {path}")
        if path.stat().st_size != item["bytes"]:
            raise AssertionError(f"byte-count mismatch for master input: {path}")
        if sha256_file(path) != item["sha256"]:
            raise AssertionError(f"hash mismatch for master input context: {path}")
    uncommented_master = "\n".join(
        line for line in master_path.read_text(encoding="utf-8").splitlines() if not line.lstrip().startswith("%")
    )
    detected_inputs = re.findall(r"\\input\{([^}]+)\}", uncommented_master)
    if detected_inputs != [item["name"] for item in input_context]:
        raise AssertionError(
            f"master input list changed: {detected_inputs} != {[item['name'] for item in input_context]}"
        )

    text_path = Path(source_by_id["SRC-TKS74-FULL-BEAUTIFUL-TEXT"]["path"])
    text = text_path.read_text(encoding="utf-8", errors="strict")
    extraction = inventory["surface_extraction"]
    pattern = re.compile(extraction["regex"])
    rows: list[dict[str, object]] = []
    for match in pattern.finditer(text):
        line_number = text.count("\n", 0, match.start()) + 1
        line_end = text.find("\n", match.start())
        if line_end < 0:
            line_end = len(text)
        anchor = " ".join(text[match.start():line_end].split())
        rows.append(
            {
                "kind": match.group(1),
                "number": match.group(2),
                "line": line_number,
                "anchor": anchor,
            }
        )
    counts = Counter(row["kind"] for row in rows)
    if len(rows) != extraction["detected_records"]:
        raise AssertionError(f"declaration count changed: {len(rows)}")
    if dict(sorted(counts.items())) != extraction["counts_by_kind"]:
        raise AssertionError(f"declaration kind counts changed: {dict(sorted(counts.items()))}")
    canonical_rows = "\n".join(
        f"{row['kind']}\t{row['number']}\t{row['line']}\t{row['anchor']}" for row in rows
    )
    if sha256_bytes(canonical_rows.encode("utf-8")) != extraction["heading_sequence_sha256"]:
        raise AssertionError("declaration heading sequence digest changed")
    key_counts = Counter((row["kind"], row["number"]) for row in rows)
    duplicates = {
        f"{kind} {number}": count
        for (kind, number), count in key_counts.items()
        if count > 1
    }
    if duplicates != extraction["duplicate_kind_number_keys"]:
        raise AssertionError(f"duplicate declaration keys changed: {duplicates}")

    text_lines_plain = text.splitlines()
    text_lines_kept = text.splitlines(keepends=True)
    placeholder_hits = [
        (index + 1, line.count("??"), line)
        for index, line in enumerate(text_lines_plain)
        if "??" in line
    ]
    placeholder = inventory["placeholder_inventory"]
    if sum(count for _, count, _ in placeholder_hits) != placeholder["occurrences"]:
        raise AssertionError("placeholder occurrence count changed")
    if [line for line, _, _ in placeholder_hits] != placeholder["line_numbers"]:
        raise AssertionError("placeholder line sequence changed")
    placeholder_canonical = "\n".join(
        f"{line}:{count}:{content}" for line, count, content in placeholder_hits
    )
    if sha256_bytes(placeholder_canonical.encode("utf-8")) != placeholder["canonical_sequence_sha256"]:
        raise AssertionError("placeholder sequence digest changed")

    allowed_statuses = {"OPEN", "VERIFIED", "RETRACTED"}
    records = corrigendum["records"]
    expected_ids = [f"TKS74-CORR-{number:03d}" for number in range(1, 30)]
    actual_ids = [record["id"] for record in records]
    if actual_ids != expected_ids:
        raise AssertionError(f"corrigendum IDs must be contiguous and ordered: {actual_ids}")
    pdf_cache: dict[tuple[str, int], str] = {}

    def pdf_page_text(source_id: str, page: int) -> str:
        key = (source_id, page)
        if key not in pdf_cache:
            source = source_by_id[source_id]
            reader = PdfReader(str(source["path"]))
            if not (1 <= page <= len(reader.pages)):
                raise AssertionError(f"invalid PDF page {page} for {source_id}")
            pdf_cache[key] = reader.pages[page - 1].extract_text() or ""
        return pdf_cache[key]

    for record in records:
        if record["status"] not in allowed_statuses:
            raise AssertionError(f"invalid status in {record['id']}: {record['status']}")
        if record["corrected_status"] not in allowed_statuses:
            raise AssertionError(
                f"invalid corrected status in {record['id']}: {record['corrected_status']}"
            )
        if record["license"] != "NOT LICENSED":
            raise AssertionError(f"record is not conservatively licensed: {record['id']}")
        for required in (
            "title",
            "record_kind",
            "original_excerpt",
            "defect_class",
            "counterexample_or_obligation",
            "corrected_statement",
            "disposition",
        ):
            if not isinstance(record.get(required), str) or not record[required].strip():
                raise AssertionError(f"missing {required} in {record['id']}")
        location = record["source_location"]
        if location["source_id"] != "SRC-TKS74-FULL-BEAUTIFUL-TEXT":
            raise AssertionError(f"unexpected line authority in {record['id']}")
        if "text_lines" in location:
            start, end = location["text_lines"]
            if not (1 <= start <= end <= len(text_lines_kept)):
                raise AssertionError(f"invalid text span in {record['id']}: {start}-{end}")
            span = "".join(text_lines_kept[start - 1 : end])
            actual_span_hash = sha256_bytes(span.encode("utf-8"))
            if actual_span_hash != location["line_span_sha256"]:
                raise AssertionError(
                    f"line-span digest mismatch in {record['id']}: {actual_span_hash}"
                )
        pages = location.get("pdf_pages")
        if pages is None and "pdf_page" in location:
            pages = [location["pdf_page"]]
        if pages:
            anchor = pdf_normalized(location["pdf_anchor"])
            if not any(anchor in pdf_normalized(pdf_page_text("SRC-TKS74-FULL-BEAUTIFUL-PDF", page)) for page in pages):
                raise AssertionError(
                    f"PDF anchor not found for {record['id']} on page(s) {pages}: {location['pdf_anchor']}"
                )
        for overlay in record["overlay_refs"]:
            source_id = overlay["source_id"]
            if source_id not in source_by_id:
                raise AssertionError(f"unknown overlay source in {record['id']}: {source_id}")
            page_text = pdf_normalized(pdf_page_text(source_id, overlay["pdf_page"]))
            if pdf_normalized(overlay["anchor"]) not in page_text:
                raise AssertionError(
                    f"overlay anchor not found for {record['id']} on {source_id} p.{overlay['pdf_page']}: {overlay['anchor']}"
                )

    if corrigendum["license"] != "NOT LICENSED" or inventory["license"] != "NOT LICENSED":
        raise AssertionError("document-level license boundary changed")

    verify_fixtures()
    status_counts = Counter(record["status"] for record in records)
    print(
        "TKS v7.4 Gate 1 verification passed: "
        f"{len(rows)} declaration headings, {len(records)} adjudicated records, "
        f"statuses={dict(sorted(status_counts.items()))}, 9 finite fixture families."
    )


if __name__ == "__main__":
    main()
