"""Exact denotational shortlex normal forms for a finite typed generator set.

No rewrite system is assumed.  Given an explicit generator order, the catalog
computes the least well-typed word in shortlex order for every reachable
finite-function denotation.  Finiteness of the carriers makes the denotation
closure finite; construction either completes or raises a resource guard
exception, so an incomplete table is never presented as canonical.
"""

from __future__ import annotations

from dataclasses import dataclass
import heapq
from itertools import count
from typing import Sequence

from .category import (
    CompositionTypeError,
    FiniteArrow,
    FiniteObject,
    ValidationError,
    _ordered_tuple,
    compose,
    identity,
)


class ClosureLimitExceeded(RuntimeError):
    """Raised instead of returning a partial normal-form catalog."""


class UnreachableDenotationError(LookupError):
    """Raised when an arrow is not generated by the declared generators."""


@dataclass(frozen=True, slots=True)
class Generator:
    label: str
    arrow: FiniteArrow

    def __post_init__(self) -> None:
        if not isinstance(self.label, str) or not self.label.strip():
            raise ValidationError("a generator needs a non-blank label")
        if not isinstance(self.arrow, FiniteArrow):
            raise ValidationError("a generator must carry a FiniteArrow")


@dataclass(frozen=True, slots=True)
class TypedWord:
    """A generator word together with the source needed for an empty word.

    The constructor validates syntax.  Categorical well-typedness is relative
    to a generator catalog and is certified by ``NormalFormCatalog.evaluate``.
    """

    start: FiniteObject
    labels: tuple[str, ...] = ()

    def __post_init__(self) -> None:
        if not isinstance(self.start, FiniteObject):
            raise ValidationError("a typed word must start at a FiniteObject")
        labels = _ordered_tuple(self.labels, "word labels")
        if any(not isinstance(label, str) or not label for label in labels):
            raise ValidationError("word labels must be non-blank strings")
        object.__setattr__(self, "labels", labels)


class NormalFormCatalog:
    """A completed finite catalog of typed denotations and their normal forms."""

    def __init__(
        self,
        objects: Sequence[FiniteObject],
        generators: Sequence[Generator],
        *,
        max_arrows: int = 100_000,
        max_frontier: int | None = None,
    ) -> None:
        self.objects = _ordered_tuple(objects, "catalog objects")
        self.generators = _ordered_tuple(generators, "catalog generators")
        if not self.objects:
            raise ValidationError("a normal-form catalog needs at least one object")
        if any(not isinstance(obj, FiniteObject) for obj in self.objects):
            raise ValidationError("every catalog object must be a FiniteObject")
        if any(not isinstance(generator, Generator) for generator in self.generators):
            raise ValidationError("every catalog generator must be a Generator")
        if len(set(self.objects)) != len(self.objects):
            raise ValidationError("catalog objects must be pairwise distinct")
        object_names = [obj.name for obj in self.objects]
        if len(set(object_names)) != len(object_names):
            raise ValidationError("catalog object names must be pairwise distinct")
        if isinstance(max_arrows, bool) or not isinstance(max_arrows, int) or max_arrows < 1:
            raise ValidationError("max_arrows must be a positive integer")
        if max_frontier is None:
            max_frontier = max_arrows
        if (
            isinstance(max_frontier, bool)
            or not isinstance(max_frontier, int)
            or max_frontier < 1
        ):
            raise ValidationError("max_frontier must be a positive integer")

        labels = [generator.label for generator in self.generators]
        if len(set(labels)) != len(labels):
            raise ValidationError("generator labels must be pairwise distinct")
        declared = set(self.objects)
        for generator in self.generators:
            if generator.arrow.source not in declared or generator.arrow.target not in declared:
                raise ValidationError(
                    f"generator {generator.label!r} references an undeclared object"
                )

        self._by_label = {generator.label: generator for generator in self.generators}
        self._rank = {generator.label: rank for rank, generator in enumerate(self.generators)}
        self._object_rank = {obj: rank for rank, obj in enumerate(self.objects)}
        self._representatives: dict[
            tuple[FiniteObject, FiniteObject, tuple[int, ...]], TypedWord
        ] = {}
        self._arrows: dict[
            tuple[FiniteObject, FiniteObject, tuple[int, ...]], FiniteArrow
        ] = {}
        self._build(max_arrows=max_arrows, max_frontier=max_frontier)

    def shortlex_key(self, word: TypedWord) -> tuple[int, tuple[int, ...], int]:
        try:
            ranks = tuple(self._rank[label] for label in word.labels)
        except KeyError as exc:
            raise ValidationError(f"unknown generator label {exc.args[0]!r}") from exc
        try:
            start_rank = self._object_rank[word.start]
        except KeyError as exc:
            raise ValidationError(f"undeclared start object {word.start.name!r}") from exc
        return (len(word.labels), ranks, start_rank)

    def evaluate(self, word: TypedWord) -> FiniteArrow:
        if word.start not in self._object_rank:
            raise ValidationError(f"undeclared start object {word.start.name!r}")
        result = identity(word.start)
        for step, label in enumerate(word.labels, start=1):
            try:
                generator = self._by_label[label]
            except KeyError as exc:
                raise ValidationError(f"unknown generator label {label!r}") from exc
            result = compose(generator.arrow, result, name=f"word-evaluation[{step}]")
        return FiniteArrow(
            name=f"word-evaluation[{len(word.labels)}]",
            source=result.source,
            target=result.target,
            mapping=result.mapping,
        )

    def normalize(self, word: TypedWord) -> TypedWord:
        denotation = self.evaluate(word)
        return self._representatives[denotation.denotation_key]

    def representative_for(self, arrow: FiniteArrow) -> TypedWord:
        try:
            return self._representatives[arrow.denotation_key]
        except KeyError as exc:
            raise UnreachableDenotationError(
                f"arrow {arrow.name!r} is not in the generated typed closure"
            ) from exc

    @property
    def denotation_count(self) -> int:
        return len(self._representatives)

    @property
    def normal_forms(self) -> tuple[TypedWord, ...]:
        return tuple(sorted(self._representatives.values(), key=self.shortlex_key))

    def _build(self, *, max_arrows: int, max_frontier: int) -> None:
        serial = count()
        frontier: list[
            tuple[
                tuple[int, tuple[int, ...], int],
                int,
                TypedWord,
                FiniteArrow,
            ]
        ] = []
        queued_denotations: set[
            tuple[FiniteObject, FiniteObject, tuple[int, ...]]
        ] = set()
        for obj in self.objects:
            if len(queued_denotations) >= max_frontier:
                raise ClosureLimitExceeded(
                    f"normal-form frontier exceeds max_frontier={max_frontier}; "
                    "no partial normal-form catalog was returned"
                )
            word = TypedWord(start=obj)
            arrow = identity(obj)
            heapq.heappush(frontier, (self.shortlex_key(word), next(serial), word, arrow))
            queued_denotations.add(arrow.denotation_key)

        while frontier:
            _, _, word, arrow = heapq.heappop(frontier)
            key = arrow.denotation_key
            queued_denotations.discard(key)
            if key in self._representatives:
                continue
            if len(self._representatives) >= max_arrows:
                raise ClosureLimitExceeded(
                    f"typed closure exceeds max_arrows={max_arrows}; no partial "
                    "normal-form catalog was returned"
                )
            self._representatives[key] = word
            self._arrows[key] = arrow

            for generator in self.generators:
                if arrow.target != generator.arrow.source:
                    continue
                extended_word = TypedWord(
                    start=word.start,
                    labels=word.labels + (generator.label,),
                )
                extended_arrow = compose(
                    generator.arrow,
                    arrow,
                    name="normal-form-closure-candidate",
                )
                extended_key = extended_arrow.denotation_key
                if (
                    extended_key not in self._representatives
                    and extended_key not in queued_denotations
                ):
                    if len(queued_denotations) >= max_frontier:
                        raise ClosureLimitExceeded(
                            f"normal-form frontier exceeds max_frontier={max_frontier}; "
                            "no partial normal-form catalog was returned"
                        )
                    heapq.heappush(
                        frontier,
                        (
                            self.shortlex_key(extended_word),
                            next(serial),
                            extended_word,
                            extended_arrow,
                        ),
                    )
                    queued_denotations.add(extended_key)
