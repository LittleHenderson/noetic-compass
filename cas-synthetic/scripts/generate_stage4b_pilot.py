_CAT_RE_LET_STAGE = re.compile(r"\blet\s+stage[ADWP]?\d", re.IGNORECASE)
_CAT_RE_CO_FORM = re.compile(r"\bCO-\d\b")
_CAT_RE_PHI_FRACTAL = re.compile(r"(?:Phi|Φ)\s*[⟨<][\d:]+[⟩>]")
_CAT_RE_RECIPE = re.compile(r"Θ\s*\(|Theta\s*\(|->\s*Ω_|->\s*Omega_")
_CAT_RE_CLUSTER = re.compile(r"NoeticCluster|StateSet|StateCluster|RelationCluster|CoverOf|PartitionOf")
_CAT_RE_MEMBERSHIP = re.compile(r"\b∈\b|\bin\s+Drives|\bin\s+Noetics")
_CAT_RE_CROSS_REG_OMEGA = re.compile(r"\([^)]*\bΩ_|=\s*\^[\d]+\^[A-Z]\|Ω_")
_CAT_RE_LET_BINDING = re.compile(r"\blet\s+[a-zA-Z_][a-zA-Z_0-9]*\s*=")
_CAT_RE_EXPORT = re.compile(r"\bexport\s+let\b")
_CAT_RE_INVERSION = re.compile(r"\^0\s*[×∘+]\s*\^9|\^2\s*[×∘+]\s*\^3|\^5\s*[×∘+]\s*\^6|\^8\s*[×∘+]\s*\^9")


def classify_grammar_category(cas: str) -> str:
    """Mirror the 10 Wave 2.5 grammar categories. Order matters."""
    if _CAT_RE_EXPORT.search(cas):
        return "diagram_export"
    if _CAT_RE_LET_STAGE.search(cas):
        return "rpm_chain"
    if _CAT_RE_RECIPE.search(cas):
        return "recipe"
    if _CAT_RE_CROSS_REG_OMEGA.search(cas):
        return "cross_register_omega"
    if _CAT_RE_PHI_FRACTAL.search(cas):
        return "fractal_sequence"
    if _CAT_RE_CLUSTER.search(cas) or _CAT_RE_MEMBERSHIP.search(cas):
        return "meta_logic_relation"
    if _CAT_RE_LET_BINDING.search(cas):
        return "let_binding"
    if _CAT_RE_CO_FORM.search(cas):
        return "binary_composition"
    if _CAT_RE_INVERSION.search(cas):
        return "inversion"
    if re.search(r"[×∘+→]", cas):
        return "binary_composition"
    if re.search(r"^\s*\^\d", cas):
        return "state_literal"
    return "other"


# ---------------------------------------------------------------------------
# Anti-jargon gate — reject if generated CAS contains common-English words
# ---------------------------------------------------------------------------

# Allowlist of substrings that legitimately appear in CAS surface (Greek
# letters used as identifiers, plus reserved CAS words).
_CAS_ALLOWED_WORDS = {
    "let", "export", "stage", "Theta", "Omega", "Phi", "Drives", "Noetics",
    "NoeticCluster", "StateCluster", "RelationCluster", "CoverOf", "PartitionOf",
    "Product", "Tuple", "Coordinate", "REJECT",
}

# If the CAS contains ANY of these common-English words (whole word), reject.
_ANTI_JARGON_BLOCKLIST = re.compile(
    r"\b(?:the|and|when|where|because|since|how|what|why|user|question|"
    r"answer|reply|please|hello|here|this|that|those|these|some|many|"
    r"feel|feeling|think|thought|wonder|know|want|need|like|love|hate)\b",
    re.IGNORECASE,
)


def anti_jargon_ok(cas: str) -> tuple[bool, str | None]:
    m = _ANTI_JARGON_BLOCKLIST.search(cas)
    if m:
        return False, f"english_word:{m.group(0)}"
    return True, None


# ---------------------------------------------------------------------------
# Copyright / long-quote detector (flag, do not reject — Codex patch 3)
# ---------------------------------------------------------------------------

# A quoted block of ≥200 chars is likely pasted from a copyrighted source.
_RE_QUOTED_BLOCK = re.compile(r"[\"'“‘]([^\"'”’]{200,})[\"'”’]", re.DOTALL)
# Known famous openings — heuristic; expand as needed.
_RE_FAMOUS_OPENINGS = re.compile(
    r"\b(?:In a hole in the ground there lived a hobbit|"
    r"It was the best of times|Call me Ishmael|All happy families are alike|"
    r"It is a truth universally acknowledged|Lorem ipsum)",
    re.IGNORECASE,
)


def detect_long_quote(question_text: str) -> str | None:
    """Return a non-empty flag string if the question likely contains
    pasted-in copyrighted/long-quoted text. Returns None otherwise.

    Codex audit `dc994e5`: flag, do not reject — preserves the corpus
    while exposing review surface for the user.
    """
    if not question_text:
        return None
    m = _RE_QUOTED_BLOCK.search(question_text)
    if m:
        return f"quoted_block_chars:{len(m.group(1))}"
    if _RE_FAMOUS_OPENINGS.search(question_text):
        return "famous_opening_detected"
    if question_text.count("\n\n") >= 2 and len(question_text) > 500:
        return f"multi_paragraph_pasted_text_len:{len(question_text)}"
    return None


