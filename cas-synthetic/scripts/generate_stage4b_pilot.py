def _read_api_key() -> str:
    # First env var (standard)
    for var in ("ANTHROPIC_API_KEY", "NC_ANTHROPIC_API_KEY"):
        v = os.environ.get(var)
        if v:
            return v
    # Then scaffold .env
    env_path = _API_DIR / ".env"
    if env_path.exists():
        for line in env_path.read_text(encoding="utf-8").splitlines():
            line = line.strip()
            if not line or line.startswith("#"):
                continue
            if line.startswith("NC_ANTHROPIC_API_KEY=") or line.startswith("ANTHROPIC_API_KEY="):
                _, _, value = line.partition("=")
                return value.strip().strip('"').strip("'")
    raise RuntimeError(
        "No API key found. Set ANTHROPIC_API_KEY or NC_ANTHROPIC_API_KEY "
        "in env, or in noetic-compass-scaffold/noetic-compass/.env"
    )


