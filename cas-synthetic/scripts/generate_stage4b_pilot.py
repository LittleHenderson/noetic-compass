"""Stage 4B pilot SDG — external question -> CAS expression.

Reads `cas-synthetic/data/stage4b/oasst2_questions_pilot.jsonl` (external
English questions only, no foreign answers), asks Haiku to propose a CAS
expression that captures the question's cognitive structure, validates via
the CAS compiler with retry, applies SFE-style gates (compile, anti-jargon,
length, judge), and writes accepted records in the Wave 2.5-compatible
JSONL shape so v0.2 retrains can consume them mixed with Wave 2.5.

Per user-ratified Stage 4 rule 2026-05-14:
    "Foreign questions can broaden CAS. Foreign answers cannot define CAS."

The foreign answer NEVER enters any output field. Only the CAS expression
generated by Haiku (and validated by our compiler) enters supervision.

Output schema mirrors Wave 2.5 `wave3_step2_5_english_descriptions_*.jsonl`
so the Stage 4A adapter can ingest the records unchanged:

    {
      "seed_id": "oasst2_q_NNNNNN",
      "source_cas": "<the CAS expression Haiku proposed and our compiler accepted>",
      "grammar_category": "<one of state_literal / binary_composition / ...>",
      "english_description": "<the original OASST2 user question>",
      "prompt_template_version": "stage4b_pilot_v1_2026_05_14",
      "validators_run": [...],
      "validators_passed": [...],
      "validators_failed_reasons": {...},
      "model_used": "claude-haiku-4-5-20251001",
      "raw_response": "<full Haiku response>",
      "input_tokens": <int>,
      "output_tokens": <int>,
      "estimated_cost_usd": <float>,
      "generated_at": "<UTC iso>",
      "wave2_5_run_id": "<not applicable — left empty for stage4b>",
      "stage4b_pilot_id": "stage4b_pilot_<TS>",
      "external_question_provenance": { ... }
    }

Hard budget cap: $5 total spend, kill-switch trips at $4.50.
"""
from __future__ import annotations

