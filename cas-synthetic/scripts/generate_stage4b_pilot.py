import json
import os
import pathlib
import re
import sys
import time
from typing import Any

# Anthropic SDK
try:
    import anthropic
except ImportError:
    print("ERROR: `anthropic` SDK not installed.", file=sys.stderr)
    sys.exit(2)

# CAS compiler bootstrap
_REPO_ROOT = pathlib.Path(__file__).resolve().parents[2]
_API_DIR = _REPO_ROOT / "noetic-compass-scaffold" / "noetic-compass"
if str(_API_DIR) not in sys.path:
    sys.path.insert(0, str(_API_DIR))

# Lazy import so the script can be smoke-tested without the compiler
def _load_compiler():
    from api.notation.compiler import compile_expression  # type: ignore
    return compile_expression


# ---------------------------------------------------------------------------
# Cost model — Haiku 4.5 pricing per Anthropic docs (2026)
# ---------------------------------------------------------------------------

HAIKU_INPUT_USD_PER_MTOK = 1.00   # $1 per 1M input tokens
HAIKU_OUTPUT_USD_PER_MTOK = 5.00  # $5 per 1M output tokens
HARD_BUDGET_USD = 5.00
KILL_SWITCH_USD = 4.50


def _haiku_cost(input_tokens: int, output_tokens: int) -> float:
    return (
        input_tokens * HAIKU_INPUT_USD_PER_MTOK / 1_000_000
        + output_tokens * HAIKU_OUTPUT_USD_PER_MTOK / 1_000_000
    )


# ---------------------------------------------------------------------------
# API key from .env (the scaffold .env has NC_ANTHROPIC_API_KEY)
# ---------------------------------------------------------------------------

def _read_api_key() -> str:
    # First env var (standard)
    for var in ("ANTHROPIC_API_KEY", "NC_ANTHROPIC_API_KEY"):
        v = os.environ.get(var)
        if v:
            return v
    # Then scaffold .env
    env_path = _API_DIR / ".env"
    if env_path.exists():
        for line in env_path.read_text(encoding="utf-8").splitlines():
            line = line.strip()
            if not line or line.startswith("#"):
                continue
            if line.startswith("NC_ANTHROPIC_API_KEY=") or line.startswith("ANTHROPIC_API_KEY="):
                _, _, value = line.partition("=")
                return value.strip().strip('"').strip("'")
    raise RuntimeError(
        "No API key found. Set ANTHROPIC_API_KEY or NC_ANTHROPIC_API_KEY "
        "in env, or in noetic-compass-scaffold/noetic-compass/.env"
    )


