CAS_TEACHING_PROMPT = """You are a Cognitive Architecture System (CAS) classifier. Your job is to map a user's English question to the closest CAS expression that captures the cognitive structure of what the question is doing or asking for.

# The 10 Noetics (authoritative — use these verbs verbatim in your reasoning)

- ^0 Idea: All things in and outside the Mind.
- ^1 Mind: Various degrees of awareness that processes, stores, outputs, and intakes Ideas.
- ^2 Positive: An Idea the Mind has an affinity for and is attracted toward.
- ^3 Negative: An Idea the Mind is adverse to and repelled by.
- ^4 Vibration: The degree to which an Idea resonates with the Mind, its impression.
- ^5 Female: A Mind impregnated with an Idea — accumulated experience, who one is.
- ^6 Male: An Idea impregnated with another Idea — compositional structure inside an Idea.
- ^7 Rhythm: The rate and pattern a Mind is exposed to an Idea, entraining/conditioning.
- ^8 Above/Cause: An Idea that triggers a different Idea than itself to come to Mind.
- ^9 Below/Effect: The Idea brought to Mind by an Above/Cause trigger.

# 4 Processing Domains

- ^P Principled (foundational values)
- ^C Cognitive (thinking)
- ^E Evaluative (judgment)
- ^O Operational (doing)

# 7 Core Drives

F1 Unity, F2 Wisdom, F3 Vitality, F4 Connection, F5 Agency, F6 Structure, F7 Purpose

# 4 Registers

|T Transcendent, |A Analytical, |f Affective, |E Embodied

# Surface forms you may emit

- State literal: `^N`, `^N^D`, `^N^D_{Fk}`, `^N^D|R`, `^N^D_{Fk}|R`
- Binary composition: `^N^D + ^M^D`, `^N^D × ^M^D`, `^N^D ∘ ^M^D`, `CO-N ∘ CO-M`
- Cross-register integration: `(^N^D|R1 × ^N^D|R2) = ^N^D|Ω_name`
- Recipe: `Θ(Ω_name) = 1*^N^D + 1*^M^D -> Ω_name`
- Set / meta-logic: `NoeticCluster{^a, ^b, ^c}`, `F1 ∈ Drives`, `|Drives|`
- Fractal sequence: `Phi⟨k1:k2:...:kn⟩` where each `ki` is 0-9
- Let binding / chain: `let X = ^N^P; let Y = ^M^C; X -> Y`
- Export: `export let name = NoeticCluster{...}`

# Your task

Given a user's English question, output **only** a single CAS expression that captures its cognitive structure. No commentary, no explanation, no markdown, no quotes around the expression. Just the raw CAS.

If the question is so general or so far from any CAS structure that no reasonable mapping exists, output literally the word REJECT and nothing else.

Examples:

User question: "Why do I feel drawn to old jazz records?"
CAS answer: ^2^C_{F4}|f

User question: "Walk me through how a decision gets made."
CAS answer: Θ(Ω_decision) = 1*^1^P + 1*^6^E -> Ω_decision

User question: "I keep thinking about the same problem over and over."
CAS answer: ^7^C_{F2}

User question: "What's the difference between the iPhone 13 and 14?"
CAS answer: REJECT

Now classify this user question:"""


JUDGE_PROMPT_TEMPLATE = """You are auditing a Cognitive Architecture System (CAS) mapping.

The user question:
{question}

The proposed CAS expression:
{cas}

Rate on a scale 1-5 how well the CAS expression captures the cognitive structure of the question:
- 5: excellent — the CAS expression precisely captures what the user is asking about (cognitive pattern, structure, or intent).
- 4: good — captures the main cognitive structure with minor weaknesses.
- 3: acceptable — captures something real about the question's structure but missing nuance.
- 2: weak — the CAS expression is technically valid but loosely related to the question.
- 1: poor — the CAS expression doesn't capture what the question is doing.

Reply with only a single digit 1-5. No commentary."""


# ---------------------------------------------------------------------------
# Grammar-category classifier (mirror Wave 2.5 categories so v0.2 mix is clean)
# ---------------------------------------------------------------------------

_CAT_RE_LET_STAGE = re.compile(r"\blet\s+stage[ADWP]?\d", re.IGNORECASE)
_CAT_RE_CO_FORM = re.compile(r"\bCO-\d\b")
_CAT_RE_PHI_FRACTAL = re.compile(r"(?:Phi|Φ)\s*[⟨<][\d:]+[⟩>]")
_CAT_RE_RECIPE = re.compile(r"Θ\s*\(|Theta\s*\(|->\s*Ω_|->\s*Omega_")
_CAT_RE_CLUSTER = re.compile(r"NoeticCluster|StateSet|StateCluster|RelationCluster|CoverOf|PartitionOf")
_CAT_RE_MEMBERSHIP = re.compile(r"\b∈\b|\bin\s+Drives|\bin\s+Noetics")
_CAT_RE_CROSS_REG_OMEGA = re.compile(r"\([^)]*\bΩ_|=\s*\^[\d]+\^[A-Z]\|Ω_")
_CAT_RE_LET_BINDING = re.compile(r"\blet\s+[a-zA-Z_][a-zA-Z_0-9]*\s*=")
_CAT_RE_EXPORT = re.compile(r"\bexport\s+let\b")
_CAT_RE_INVERSION = re.compile(r"\^0\s*[×∘+]\s*\^9|\^2\s*[×∘+]\s*\^3|\^5\s*[×∘+]\s*\^6|\^8\s*[×∘+]\s*\^9")


def classify_grammar_category(cas: str) -> str:
    """Mirror the 10 Wave 2.5 grammar categories. Order matters."""
    if _CAT_RE_EXPORT.search(cas):
        return "diagram_export"
    if _CAT_RE_LET_STAGE.search(cas):
        return "rpm_chain"
    if _CAT_RE_RECIPE.search(cas):
        return "recipe"
    if _CAT_RE_CROSS_REG_OMEGA.search(cas):
        return "cross_register_omega"
    if _CAT_RE_PHI_FRACTAL.search(cas):
        return "fractal_sequence"
    if _CAT_RE_CLUSTER.search(cas) or _CAT_RE_MEMBERSHIP.search(cas):
        return "meta_logic_relation"
    if _CAT_RE_LET_BINDING.search(cas):
        return "let_binding"
    if _CAT_RE_CO_FORM.search(cas):
        return "binary_composition"
    if _CAT_RE_INVERSION.search(cas):
        return "inversion"
    if re.search(r"[×∘+→]", cas):
        return "binary_composition"
    if re.search(r"^\s*\^\d", cas):
        return "state_literal"
    return "other"


# ---------------------------------------------------------------------------
# Anti-jargon gate — reject if generated CAS contains common-English words
# ---------------------------------------------------------------------------

# Allowlist of substrings that legitimately appear in CAS surface (Greek
# letters used as identifiers, plus reserved CAS words).
_CAS_ALLOWED_WORDS = {
    "let", "export", "stage", "Theta", "Omega", "Phi", "Drives", "Noetics",
    "NoeticCluster", "StateCluster", "RelationCluster", "CoverOf", "PartitionOf",
    "Product", "Tuple", "Coordinate", "REJECT",
}

# If the CAS contains ANY of these common-English words (whole word), reject.
_ANTI_JARGON_BLOCKLIST = re.compile(
    r"\b(?:the|and|when|where|because|since|how|what|why|user|question|"
    r"answer|reply|please|hello|here|this|that|those|these|some|many|"
    r"feel|feeling|think|thought|wonder|know|want|need|like|love|hate)\b",
    re.IGNORECASE,
)


def anti_jargon_ok(cas: str) -> tuple[bool, str | None]:
    m = _ANTI_JARGON_BLOCKLIST.search(cas)
    if m:
        return False, f"english_word:{m.group(0)}"
    return True, None


# ---------------------------------------------------------------------------
# Main pipeline
# ---------------------------------------------------------------------------

def _utc_now() -> str:
    return _dt.datetime.now(_dt.UTC).strftime("%Y-%m-%dT%H:%M:%SZ")


def call_haiku_propose(client: Any, question: str, model: str, max_retries: int = 3) -> dict:
    """Call Haiku to propose a CAS expression. Returns dict with full call metadata."""
    user_msg = f"{CAS_TEACHING_PROMPT}\n\n{question}"
    last_err = None
    for attempt in range(max_retries + 1):
        try:
            resp = client.messages.create(
                model=model,
                max_tokens=256,
                temperature=0.3,
                messages=[{"role": "user", "content": user_msg}],
            )
            cas = "".join(b.text for b in resp.content if hasattr(b, "text")).strip()
            return {
                "cas": cas,
                "input_tokens": resp.usage.input_tokens,
                "output_tokens": resp.usage.output_tokens,
                "model": model,
                "attempt": attempt,
                "error": None,
            }
        except Exception as exc:
            last_err = str(exc)[:200]
            time.sleep(1.0 * (attempt + 1))
    return {
        "cas": "",
        "input_tokens": 0,
        "output_tokens": 0,
        "model": model,
        "attempt": max_retries,
        "error": last_err or "exhausted_retries",
    }


def call_haiku_judge(client: Any, question: str, cas: str, model: str) -> dict:
    """Call Haiku judge to rate the mapping 1-5."""
    user_msg = JUDGE_PROMPT_TEMPLATE.format(question=question, cas=cas)
    try:
        resp = client.messages.create(
            model=model,
            max_tokens=8,
            temperature=0.0,
            messages=[{"role": "user", "content": user_msg}],
        )
        raw = "".join(b.text for b in resp.content if hasattr(b, "text")).strip()
        # Extract first digit
        m = re.search(r"[1-5]", raw)
        score = int(m.group(0)) if m else 0
        return {
            "score": score,
            "raw": raw,
            "input_tokens": resp.usage.input_tokens,
            "output_tokens": resp.usage.output_tokens,
            "error": None,
        }
    except Exception as exc:
        return {
            "score": 0,
            "raw": "",
            "input_tokens": 0,
            "output_tokens": 0,
            "error": str(exc)[:200],
        }


def main(argv: list[str] | None = None) -> int:
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument("--in", dest="in_path", type=str,
                   default="cas-synthetic/data/stage4b/oasst2_questions_pilot.jsonl")
    p.add_argument("--out-dir", type=str, default="cas-synthetic/data/stage4b")
    p.add_argument("--model", type=str, default="claude-haiku-4-5-20251001")
    p.add_argument("--limit", type=int, default=0,
                   help="0 = process all; otherwise cap at N records for smoke")
    p.add_argument("--judge-floor", type=int, default=3,
                   help="Minimum judge score to accept (1-5 scale)")
    p.add_argument("--max-cas-len", type=int, default=256)
    p.add_argument("--min-cas-len", type=int, default=2)
    p.add_argument("--seed", type=int, default=4242)
    p.add_argument("--skip-judge", action="store_true",
                   help="Skip Haiku judge call (cheaper smoke; accept on compile+anti-jargon)")
    args = p.parse_args(argv)

    api_key = _read_api_key()
    client = anthropic.Client(api_key=api_key)
    compile_expression = _load_compiler()

    in_path = pathlib.Path(args.in_path)
    if not in_path.exists():
        print(f"ERROR: input not found: {in_path}", file=sys.stderr)
        return 2

    records = []
    with in_path.open("r", encoding="utf-8") as fh:
        for line in fh:
            line = line.strip()
            if not line:
                continue
            records.append(json.loads(line))
    if int(args.limit) > 0:
        records = records[: int(args.limit)]
    print(f"loaded {len(records)} questions from {in_path}")

    ts = _dt.datetime.now(_dt.UTC).strftime("%Y%m%dT%H%M%SZ")
    pilot_id = f"stage4b_pilot_{ts}"
    out_dir = pathlib.Path(args.out_dir)
    out_dir.mkdir(parents=True, exist_ok=True)
    accepted_path = out_dir / f"{pilot_id}_accepted.jsonl"
    rejected_path = out_dir / f"{pilot_id}_rejected.jsonl"
    manifest_path = out_dir / f"{pilot_id}_manifest.json"

    reject_reasons: collections.Counter[str] = collections.Counter()
    cat_counts: collections.Counter[str] = collections.Counter()
    total_cost = 0.0
    n_haiku_propose_calls = 0
    n_haiku_judge_calls = 0
    accepted_records: list[dict] = []
    rejected_records: list[dict] = []
    t_start = time.time()

    with accepted_path.open("w", encoding="utf-8") as f_acc, rejected_path.open("w", encoding="utf-8") as f_rej:
        for i, q_rec in enumerate(records):
            # Budget kill-switch
            if total_cost >= KILL_SWITCH_USD:
                print(f"KILL_SWITCH: total_cost ${total_cost:.4f} >= ${KILL_SWITCH_USD:.2f}", file=sys.stderr)
                break
            question = q_rec["question_text"]
            seed_id = q_rec["id"]

            # Step 1: Haiku proposes CAS
            propose_t0 = time.time()
            prop = call_haiku_propose(client, question, args.model, max_retries=3)
            n_haiku_propose_calls += 1
            total_cost += _haiku_cost(prop["input_tokens"], prop["output_tokens"])
            propose_elapsed = time.time() - propose_t0

            validators_run = ["haiku_propose"]
            validators_passed: list[str] = []
            validators_failed: dict[str, str] = {}
            judge_result: dict[str, Any] | None = None

            raw_response = prop["cas"]
            cas = raw_response.strip()

            # Strip common LLM wrapping artifacts
            if cas.startswith("```") and cas.endswith("```"):
                cas = cas.strip("`").strip()
            cas = cas.lstrip("CAS answer:").strip()

            if prop["error"]:
                validators_failed["haiku_propose"] = prop["error"]
            else:
                validators_passed.append("haiku_propose")

            # Step 2: Explicit REJECT response
            if cas.upper().strip() == "REJECT":
                validators_failed["haiku_self_reject"] = "haiku returned REJECT"

            # Step 3: Length sanity
            validators_run.append("length_sanity")
            if not validators_failed:
                if len(cas) < int(args.min_cas_len):
                    validators_failed["length_sanity"] = f"too_short:{len(cas)}"
                elif len(cas) > int(args.max_cas_len):
                    validators_failed["length_sanity"] = f"too_long:{len(cas)}"
                else:
                    validators_passed.append("length_sanity")

            # Step 4: Anti-jargon
            validators_run.append("anti_jargon")
            if not validators_failed:
                aj_ok, aj_err = anti_jargon_ok(cas)
                if not aj_ok:
                    validators_failed["anti_jargon"] = aj_err
                else:
                    validators_passed.append("anti_jargon")

            # Step 5: Compile (load-bearing)
            validators_run.append("cas_compile")
            compile_err: str | None = None
            grammar_category = "?"
            if not validators_failed:
                try:
                    art = compile_expression(cas)
                    if getattr(art, "valid", False):
                        validators_passed.append("cas_compile")
                        grammar_category = classify_grammar_category(cas)
                    else:
                        compile_err = (getattr(art, "error", "") or "compile_invalid")[:240]
                        validators_failed["cas_compile"] = compile_err
                except Exception as exc:
                    compile_err = str(exc)[:240]
                    validators_failed["cas_compile"] = compile_err

            # Step 6: Judge (only if everything else passed and not --skip-judge)
            if not validators_failed and not args.skip_judge:
                validators_run.append("haiku_judge")
                judge_result = call_haiku_judge(client, question, cas, args.model)
                n_haiku_judge_calls += 1
                total_cost += _haiku_cost(judge_result["input_tokens"], judge_result["output_tokens"])
                if judge_result["error"]:
                    validators_failed["haiku_judge"] = judge_result["error"]
                elif judge_result["score"] < int(args.judge_floor):
                    validators_failed["haiku_judge"] = f"score_below_floor:{judge_result['score']}"
                else:
                    validators_passed.append("haiku_judge")

            # Build output record
            out_rec = {
                "seed_id": seed_id,
                "source_cas": cas if not validators_failed else raw_response,
                "grammar_category": grammar_category,
                "english_description": question,
                "prompt_template_version": "stage4b_pilot_v1_2026_05_14",
                "validators_run": validators_run,
                "validators_passed": validators_passed,
                "validators_failed_reasons": validators_failed,
                "model_used": args.model,
                "raw_response": raw_response,
                "input_tokens": prop["input_tokens"],
                "output_tokens": prop["output_tokens"],
                "estimated_cost_usd": _haiku_cost(prop["input_tokens"], prop["output_tokens"]),
                "generated_at": _utc_now(),
                "wave2_5_run_id": "",
                "stage4b_pilot_id": pilot_id,
                "judge_result": judge_result,
                "external_question_provenance": q_rec.get("source", {}),
            }

            if validators_failed:
                first_reason = next(iter(validators_failed.keys()))
                reject_reasons[first_reason] += 1
                f_rej.write(json.dumps(out_rec, ensure_ascii=False) + "\n")
                rejected_records.append(out_rec)
            else:
                cat_counts[grammar_category] += 1
                f_acc.write(json.dumps(out_rec, ensure_ascii=False) + "\n")
                accepted_records.append(out_rec)

            if (i + 1) % 10 == 0 or i < 5:
                print(
                    f"[{i+1}/{len(records)}] cost=${total_cost:.4f} "
                    f"accepted={len(accepted_records)} rejected={len(rejected_records)} "
                    f"last_reject={list(validators_failed.keys())[0] if validators_failed else '-'}"
                )

    elapsed_total = time.time() - t_start
    n_attempted = len(accepted_records) + len(rejected_records)

    manifest = {
        "schema_version": "stage4b_pilot.v1",
        "pilot_id": pilot_id,
        "created_at": _utc_now(),
        "input_file": str(in_path),
        "input_sha256": hashlib.sha256(in_path.read_bytes()).hexdigest(),
        "accepted_file": str(accepted_path),
        "rejected_file": str(rejected_path),
        "n_attempted": n_attempted,
        "n_accepted": len(accepted_records),
        "n_rejected": len(rejected_records),
        "acceptance_rate": (len(accepted_records) / n_attempted) if n_attempted > 0 else 0.0,
        "reject_reasons": dict(reject_reasons.most_common()),
        "category_spread": dict(cat_counts.most_common()),
        "model_used": args.model,
        "judge_floor": int(args.judge_floor),
        "n_haiku_propose_calls": n_haiku_propose_calls,
        "n_haiku_judge_calls": n_haiku_judge_calls,
        "total_cost_usd": round(total_cost, 6),
        "budget_cap_usd": HARD_BUDGET_USD,
        "kill_switch_usd": KILL_SWITCH_USD,
        "elapsed_seconds": elapsed_total,
        "rule": (
            "external questions only; foreign answer text NEVER stored; "
            "CAS supervision is Haiku-proposed and compiler-validated only"
        ),
    }
    with manifest_path.open("w", encoding="utf-8") as fh:
        json.dump(manifest, fh, indent=2, sort_keys=True)

    print(json.dumps({
        "event": "stage4b_pilot_complete",
        "n_attempted": n_attempted,
        "n_accepted": len(accepted_records),
        "n_rejected": len(rejected_records),
        "acceptance_rate": manifest["acceptance_rate"],
        "total_cost_usd": round(total_cost, 4),
        "elapsed_seconds": round(elapsed_total, 2),
        "accepted_path": str(accepted_path),
        "rejected_path": str(rejected_path),
        "manifest_path": str(manifest_path),
        "top_reject_reasons": dict(reject_reasons.most_common(5)),
        "category_spread": dict(cat_counts.most_common(10)),
    }, sort_keys=True))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
