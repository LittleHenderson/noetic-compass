def load_tks_f28_definitions(path: Path) -> tuple[DefinitionRecord, ...]:
    payload = read_json(path)
    if payload.get("schema_version") != "tks_owner_provided_axis_definitions.v1":
        raise ValueError("TKS definition source schema_version is not owner-provided v1")
    items = payload.get("tks_28_foundations")
    if not isinstance(items, list):
        raise ValueError("TKS source requires tks_28_foundations")
    by_label: dict[str, DefinitionRecord] = {}
    for item in items:
        if not isinstance(item, dict):
            raise ValueError("Every TKS Foundation definition must be an object")
        legacy_code = str(item.get("code") or "").strip()
        label = legacy_code_to_foundation(legacy_code)
        title = str(item.get("title") or "").strip()
        definition = str(item.get("definition") or "").strip()
        if not title or not definition:
            raise ValueError(f"Definition {legacy_code!r} requires non-empty title and definition")
        if label in by_label:
            raise ValueError(f"Duplicate Foundation definition: {label}")
        by_label[label] = DefinitionRecord(
            label=label,
            legacy_code=legacy_code,
            title=title,
            definition=definition,
            prototype_text=f"{title}\n{definition}",
        )
    missing = sorted(set(FOUNDATION_LABELS) - set(by_label))
    extra = sorted(set(by_label) - set(FOUNDATION_LABELS))
    if missing or extra or len(items) != 28:
        raise ValueError(f"Foundation-28 definition mismatch: missing={missing}, extra={extra}")
    return tuple(by_label[label] for label in FOUNDATION_LABELS)


def legacy_code_to_foundation(code: str) -> str:
    match = re.fullmatch(r"([1-7])([a-d])", str(code).strip())
    if not match:
        raise ValueError(f"Invalid legacy TKS Foundation code: {code!r}")
    drive, world = match.groups()
    return f"F{drive}|{LEGACY_REGISTER_MAP[world]}"


def build_compact_definition_records() -> tuple[DefinitionRecord, ...]:
    records: list[DefinitionRecord] = []
    reverse_legacy = {value: key for key, value in LEGACY_REGISTER_MAP.items()}
    for drive in (f"F{index}" for index in range(1, 8)):
        for register in REGISTER_ORDER:
            label = f"{drive}|{register}"
            title = f"{DRIVES[drive]['name']} / {REGISTERS[register]['name']}"
            definition = (
                f"Drive concern: {DRIVES[drive]['concern']}. "
                f"Register lens: {REGISTERS[register]['lens']}. "
                f"Register cue: {REGISTERS[register]['cue']}."
            )
            records.append(
                DefinitionRecord(
                    label=label,
                    legacy_code=f"{drive[1:]}{reverse_legacy[register]}",
                    title=title,
                    definition=definition,
                    prototype_text=f"{title}\n{definition}",
                )
            )
    return tuple(records)


def validate_arm_set(arms: Sequence[DefinitionArm]) -> None:
    names = [arm.name for arm in arms]
    if len(names) != len(set(names)):
        raise ValueError(f"Duplicate arm names: {names}")
    required = {ORIGINAL_ARM_NAME, OPERATIONAL_ARM_NAME, COMPACT_ARM_NAME}
    missing = sorted(required - set(names))
    if missing:
        raise ValueError(f"Required diagnostic arms are missing: {missing}")
    selection_names = {arm.name for arm in arms if arm.include_in_shared_layer_selection}
    expected_selection = {ORIGINAL_ARM_NAME, OPERATIONAL_ARM_NAME}
    if selection_names != expected_selection:
        raise ValueError(
            "Shared-layer selection must use exactly the D3 original and A124 operational rewrite; "
            f"got {sorted(selection_names)}"
        )
    for arm in arms:
        labels = tuple(record.label for record in arm.definitions)
        if labels != FOUNDATION_LABELS:
            raise ValueError(f"Arm {arm.name} does not use the canonical Foundation-28 ordering")
    derive_definition_change_contract(arms)


def derive_definition_change_contract(arms: Sequence[DefinitionArm]) -> dict[str, Any]:
    by_name = {arm.name: arm for arm in arms}
    if ORIGINAL_ARM_NAME not in by_name or OPERATIONAL_ARM_NAME not in by_name:
        raise ValueError("D3/A124 definition change contract requires both canonical source arms")
    original = by_name[ORIGINAL_ARM_NAME]
    operational = by_name[OPERATIONAL_ARM_NAME]
    original_by_label = {record.label: record for record in original.definitions}
    operational_by_label = {record.label: record for record in operational.definitions}
    changed = tuple(
        label
        for label in FOUNDATION_LABELS
        if (
            original_by_label[label].title,
            original_by_label[label].definition,
        )
        != (
            operational_by_label[label].title,
            operational_by_label[label].definition,
        )
    )
    if set(changed) != set(PREREGISTERED_CHANGED_FOUNDATIONS):
        raise ValueError(
            "D3/A124 changed-definition set does not match the preregistered 8 labels: "
            f"expected={list(PREREGISTERED_CHANGED_FOUNDATIONS)}, derived={list(changed)}"
        )
    changed_legacy = tuple(original_by_label[label].legacy_code for label in changed)
    if set(changed_legacy) != set(CHANGED_LEGACY_CODES):
        raise ValueError(
            "D3/A124 changed legacy-code set mismatch: "
            f"expected={list(CHANGED_LEGACY_CODES)}, derived={list(changed_legacy)}"
        )
    unchanged = tuple(label for label in FOUNDATION_LABELS if label not in changed)
    if len(changed) != 8 or len(unchanged) != 20 or set(changed) & set(unchanged):
        raise ValueError("D3/A124 changed-8 and unchanged-20 partitions are invalid")
    return {
        "status": "PREREGISTERED_CHANGED_8_FAIL_CLOSED",
        "comparison": f"{ORIGINAL_ARM_NAME} vs {OPERATIONAL_ARM_NAME}",
        "original_source_sha256": original.source_sha256,
        "operational_source_sha256": operational.source_sha256,
        "changed_legacy_codes_preregistered": list(CHANGED_LEGACY_CODES),
        "changed_foundations_preregistered": list(PREREGISTERED_CHANGED_FOUNDATIONS),
        "changed_foundations_derived_canonical_order": list(changed),
        "unchanged_foundations_derived_canonical_order": list(unchanged),
        "changed_count": len(changed),
        "unchanged_count": len(unchanged),
        "partition_sha256": sha256_json({"changed": changed, "unchanged": unchanged}),
    }


