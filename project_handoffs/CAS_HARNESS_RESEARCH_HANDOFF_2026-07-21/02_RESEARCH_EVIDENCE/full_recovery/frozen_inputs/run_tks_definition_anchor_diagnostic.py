def deterministic_derangement(labels: Sequence[str], seed: int) -> list[str]:
    original = np.asarray(labels)
    rng = np.random.default_rng(stable_seed(seed, "definition-label-derangement"))
    for _attempt in range(10000):
        shuffled = rng.permutation(original)
        if np.all(shuffled != original):
            return shuffled.tolist()
    raise RuntimeError("Could not construct deterministic label derangement")


def group_positions(group_ids: np.ndarray) -> tuple[np.ndarray, dict[str, np.ndarray]]:
    groups = np.unique(np.asarray(group_ids).astype(str))
    if len(groups) < 1:
        raise ValueError("Cluster bootstrap requires at least one group")
    positions = {
        group: np.flatnonzero(np.asarray(group_ids).astype(str) == group) for group in groups
    }
    return groups, positions


def resample_group_indices(
    groups: np.ndarray,
    positions: dict[str, np.ndarray],
    rng: np.random.Generator,
) -> np.ndarray:
    sampled = rng.choice(groups, size=len(groups), replace=True)
    return np.concatenate([positions[str(group)] for group in sampled])


def percentile_interval(values: np.ndarray) -> list[float]:
    low, high = np.quantile(values, [0.025, 0.975])
    return [float(low), float(high)]


