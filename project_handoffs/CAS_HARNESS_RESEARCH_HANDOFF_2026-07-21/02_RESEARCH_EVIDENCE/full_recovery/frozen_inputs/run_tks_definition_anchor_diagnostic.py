"""Run a source-bound zero-shot TKS definition-anchor diagnostic.

This diagnostic asks a narrow question: when the same pinned open-weight model
reads definition texts and a shared prompt bank, which definition arm produces
hidden-state anchors that are most aligned with the expected Foundation-28
labels?  It is intentionally *not* a trained semantic probe, a causal-control
result, a universality result, or a licensed CAS Harness verdict.

The implementation fails closed on source hashes, captures evaluation prompts
once for every arm, hooks complete transformer block outputs (never MLP-only
outputs), and retains both mean-token and last-token raw vectors in NPZ form.
"""

