def load_evaluation_scenarios(
    stage7_path: Path,
    sensitivity_path: Path,
    *,
    allow_unpinned_canary: bool,
) -> tuple[list[EvalScenario], dict[str, Any]]:
    stage7_resolved = stage7_path.resolve()
    sensitivity_resolved = sensitivity_path.resolve()
    stage7_sha256 = sha256_file(stage7_resolved)
    sensitivity_sha256 = sha256_file(sensitivity_resolved)
    banks_pinned = (
        stage7_sha256 == STAGE7_BANK_SHA256
        and sensitivity_sha256 == FOUNDATION28_V0_BANK_SHA256
    )
    if not banks_pinned and not allow_unpinned_canary:
        raise ValueError(
            "Scenario bank hash mismatch. Expected fixed Stage-7 and Foundation-28 v0 sources; "
            f"got stage7={stage7_sha256}, sensitivity={sensitivity_sha256}."
        )
    stage7 = load_stage7_eval_bank(stage7_resolved)
    sensitivity = load_sensitivity_eval_bank(sensitivity_resolved, minimum_variant=8)
    scenarios = stage7 + sensitivity
    split_counts = Counter(scenario.split for scenario in scenarios)
    provenance = {
        "stage7": {
            "path": str(stage7_resolved),
            "sha256": stage7_sha256,
            "expected_sha256": STAGE7_BANK_SHA256,
            "included_splits": ["val", "test"],
            "excluded_split": "train",
            "scenario_count": len(stage7),
            "group_id_source": "metadata.counterfactual_pair_id",
        },
        "source_derived_sensitivity_foundation28_v0": {
            "path": str(sensitivity_resolved),
            "sha256": sensitivity_sha256,
            "expected_sha256": FOUNDATION28_V0_BANK_SHA256,
            "included_variant_rule": "metadata.variant >= 8",
            "scenario_count": len(sensitivity),
            "group_id_source": (
                "expected_cas_axes.foundation/source-generator unit; variants 8 and 9 stay "
                "in the same cluster"
            ),
        },
        "split_counts": dict(sorted(split_counts.items())),
        "group_integrity": build_group_integrity_summary(scenarios),
        "common_evaluation_bank": True,
        "banks_pinned": banks_pinned,
        "canary_override": bool(not banks_pinned and allow_unpinned_canary),
        "integrity_pinned": banks_pinned,
        "source_generator_bias": SOURCE_GENERATOR_BIAS,
    }
    return scenarios, provenance


def load_stage7_eval_bank(path: Path) -> list[EvalScenario]:
    payload = read_json(path)
    items = payload.get("scenarios")
    if not isinstance(items, list):
        raise ValueError("Stage-7 bank requires a scenarios list")
    scenarios: list[EvalScenario] = []
    for item in items:
        if not isinstance(item, dict):
            raise ValueError("Every Stage-7 scenario must be an object")
        metadata = item.get("metadata")
        axes = item.get("expected_cas_axes")
        if not isinstance(metadata, dict) or not isinstance(axes, dict):
            raise ValueError("Stage-7 scenarios require metadata and expected_cas_axes")
        split = str(metadata.get("split") or "").strip()
        if split not in {"train", "val", "test"}:
            raise ValueError(f"Unknown Stage-7 split: {split!r}")
        if split == "train":
            continue
        group_id = str(metadata.get("counterfactual_pair_id") or "").strip()
        if not group_id:
            raise ValueError("Stage-7 val/test scenarios require metadata.counterfactual_pair_id")
        scenarios.append(
            parse_eval_scenario(
                item,
                split=f"stage7_{split}",
                bank="stage7_rolebound_fixed",
                group_id=group_id,
                group_id_source="metadata.counterfactual_pair_id",
            )
        )
    validate_split_balance(scenarios, required_splits={"stage7_val", "stage7_test"})
    validate_stage7_group_integrity(scenarios)
    return scenarios


def load_sensitivity_eval_bank(path: Path, *, minimum_variant: int) -> list[EvalScenario]:
    payload = read_json(path)
    items = payload.get("scenarios")
    if not isinstance(items, list):
        raise ValueError("Foundation-28 v0 sensitivity bank requires a scenarios list")
    scenarios: list[EvalScenario] = []
    observed_variants: set[int] = set()
    for item in items:
        if not isinstance(item, dict):
            raise ValueError("Every sensitivity-bank scenario must be an object")
        metadata = item.get("metadata")
        if not isinstance(metadata, dict):
            raise ValueError("Sensitivity-bank scenarios require metadata")
        try:
            variant = int(metadata.get("variant"))
        except (TypeError, ValueError) as exc:
            raise ValueError("Sensitivity-bank scenarios require integer metadata.variant") from exc
        if variant < minimum_variant:
            continue
        observed_variants.add(variant)
        scenario_id = str(item.get("id") or item.get("scenario_id") or "").strip()
        if not scenario_id:
            raise ValueError("Sensitivity-bank scenarios require id")
        axes = item.get("expected_cas_axes")
        if not isinstance(axes, dict):
            raise ValueError("Sensitivity-bank scenarios require expected_cas_axes")
        foundation = str(axes.get("foundation") or "").strip()
        if foundation not in FOUNDATION_LABELS:
            raise ValueError(f"Invalid sensitivity-bank Foundation label: {foundation!r}")
        scenarios.append(
            parse_eval_scenario(
                item,
                split=SENSITIVITY_SPLIT,
                bank="foundation28_v0_source_derived_sensitivity",
                group_id=f"foundation28_v0_source_unit_{foundation}",
                group_id_source="expected_cas_axes.foundation/source_generator_unit",
            )
        )
    if not scenarios or min(observed_variants) < minimum_variant:
        raise ValueError(f"No sensitivity-bank scenarios found for variant >= {minimum_variant}")
    validate_split_balance(scenarios, required_splits={SENSITIVITY_SPLIT})
    validate_sensitivity_group_integrity(scenarios)
    return scenarios


def parse_eval_scenario(
    item: dict[str, Any],
    *,
    split: str,
    bank: str,
    group_id: str,
    group_id_source: str,
) -> EvalScenario:
    axes = item.get("expected_cas_axes")
    if not isinstance(axes, dict):
        raise ValueError("Scenario requires expected_cas_axes")
    drive = str(axes.get("drive") or "").strip()
    register = str(axes.get("register") or "").strip()
    foundation = str(axes.get("foundation") or "").strip()
    if drive not in DRIVE_LABELS or register not in REGISTER_LABELS:
        raise ValueError(f"Invalid drive/register labels: {drive!r}/{register!r}")
    if foundation != f"{drive}|{register}" or foundation not in FOUNDATION_LABELS:
        raise ValueError(f"Invalid Foundation label: {foundation!r}")
    scenario_id = str(item.get("id") or item.get("scenario_id") or "").strip()
    prompt = str(item.get("prompt") or "").strip()
    if not scenario_id or not prompt:
        raise ValueError("Scenario requires non-empty id and prompt")
    return EvalScenario(
        scenario_id=scenario_id,
        prompt=prompt,
        foundation=foundation,
        drive=drive,
        register=register,
        split=split,
        bank=bank,
        group_id=group_id,
        group_id_source=group_id_source,
    )


def validate_split_balance(
    scenarios: Sequence[EvalScenario],
    *,
    required_splits: set[str],
) -> None:
    by_split: dict[str, Counter[str]] = {}
    ids: set[str] = set()
    for scenario in scenarios:
        if scenario.scenario_id in ids:
            raise ValueError(f"Duplicate scenario id: {scenario.scenario_id}")
        ids.add(scenario.scenario_id)
        by_split.setdefault(scenario.split, Counter())[scenario.foundation] += 1
    if set(by_split) != required_splits:
        raise ValueError(f"Split mismatch: expected {sorted(required_splits)}, got {sorted(by_split)}")
    for split, counts in by_split.items():
        if set(counts) != set(FOUNDATION_LABELS):
            raise ValueError(f"{split} does not contain all 28 Foundation labels")
        if len(set(counts.values())) != 1:
            raise ValueError(f"{split} is not Foundation-28 balanced: {dict(counts)}")


def validate_stage7_group_integrity(scenarios: Sequence[EvalScenario]) -> None:
    groups_by_split: dict[str, Counter[str]] = {}
    for scenario in scenarios:
        groups_by_split.setdefault(scenario.split, Counter())[scenario.group_id] += 1
    for split in ("stage7_val", "stage7_test"):
        sizes = set(groups_by_split.get(split, {}).values())
        if sizes != {2}:
            raise ValueError(f"{split} counterfactual groups must each contain exactly 2 rows")
    if set(groups_by_split["stage7_val"]) & set(groups_by_split["stage7_test"]):
        raise ValueError("Stage7 validation and test group IDs overlap")


def validate_sensitivity_group_integrity(scenarios: Sequence[EvalScenario]) -> None:
    groups = Counter(scenario.group_id for scenario in scenarios)
    if len(groups) != 28 or set(groups.values()) != {2}:
        raise ValueError(
            "Sensitivity bank must have 28 Foundation/source-unit groups with variants 8/9 "
            "together (2 rows per group)"
        )
    for group_id, rows in _group_scenarios(scenarios).items():
        foundations = {row.foundation for row in rows}
        if len(foundations) != 1:
            raise ValueError(f"Sensitivity group crosses Foundations: {group_id}")


def build_group_integrity_summary(
    scenarios: Sequence[EvalScenario],
) -> dict[str, Any]:
    summary = {}
    for split in sorted({scenario.split for scenario in scenarios}):
        split_rows = [scenario for scenario in scenarios if scenario.split == split]
        group_sizes = Counter(scenario.group_id for scenario in split_rows)
        summary[split] = {
            "row_count": len(split_rows),
            "group_count": len(group_sizes),
            "group_size_distribution": dict(
                sorted(Counter(group_sizes.values()).items())
            ),
        }
    stage_val_groups = {
        scenario.group_id for scenario in scenarios if scenario.split == "stage7_val"
    }
    stage_test_groups = {
        scenario.group_id for scenario in scenarios if scenario.split == "stage7_test"
    }
    summary["stage7_val_test_group_overlap_count"] = len(
        stage_val_groups & stage_test_groups
    )
    return summary


def _group_scenarios(
    scenarios: Sequence[EvalScenario],
) -> dict[str, list[EvalScenario]]:
    grouped: dict[str, list[EvalScenario]] = {}
    for scenario in scenarios:
        grouped.setdefault(scenario.group_id, []).append(scenario)
    return grouped


def load_model(args: Any) -> tuple[Any, Any, dict[str, Any]]:
    import torch
    from transformers import AutoConfig, AutoModelForCausalLM, AutoTokenizer

    dtype = resolve_torch_dtype(torch, args.torch_dtype)
    config = AutoConfig.from_pretrained(
        args.model_id,
        revision=args.model_revision,
        trust_remote_code=args.trust_remote_code,
    )
    tokenizer = AutoTokenizer.from_pretrained(
        args.model_id,
        revision=args.model_revision,
        trust_remote_code=args.trust_remote_code,
    )
    model = AutoModelForCausalLM.from_pretrained(
        args.model_id,
        revision=args.model_revision,
        torch_dtype=dtype,
        device_map=args.device_map,
        low_cpu_mem_usage=True,
        trust_remote_code=args.trust_remote_code,
    )
    model.eval()
    resolved_commits = {
        str(value).lower()
        for value in (
            getattr(config, "_commit_hash", None),
            getattr(getattr(model, "config", None), "_commit_hash", None),
            getattr(tokenizer, "_commit_hash", None),
        )
        if value
    }
    requested = str(args.model_revision).lower()
    artifact_provenance = resolve_hf_artifact_provenance(
        args.model_id,
        args.model_revision,
        trust_remote_code=args.trust_remote_code,
    )
    validate_resolved_model_revision(requested, resolved_commits, artifact_provenance)
    return model, tokenizer, {
        "model_id": args.model_id,
        "requested_revision": args.model_revision,
        "resolved_commit_hashes": sorted(resolved_commits),
        "resolved_artifacts": artifact_provenance,
        "architectures": list(getattr(config, "architectures", []) or []),
        "model_type": getattr(config, "model_type", None),
        "hidden_size": getattr(config, "hidden_size", None),
        "num_hidden_layers": getattr(config, "num_hidden_layers", None),
        "num_attention_heads": getattr(config, "num_attention_heads", None),
        "vocab_size": getattr(config, "vocab_size", None),
        "torch_dtype": str(dtype) if dtype is not None else "auto",
        "device_map": args.device_map,
        "parameter_count": count_parameters(model),
        "trust_remote_code": bool(args.trust_remote_code),
    }


def capture_text_vectors(
    *,
    model: Any,
    tokenizer: Any,
    texts: Sequence[str],
    selected_layers: Sequence[tuple[int, Any]],
    max_length: int,
    progress_prefix: str,
) -> tuple[np.ndarray, np.ndarray, np.ndarray, np.ndarray]:
    if not texts:
        raise ValueError("No texts supplied for hidden-state capture")
    mean_rows: list[np.ndarray] = []
    last_rows: list[np.ndarray] = []
    token_counts: list[int] = []
    token_id_hashes: list[str] = []
    for ordinal, text in enumerate(texts, start=1):
        mean_vectors, last_vectors, token_count, token_id_sha256 = capture_single_text_vectors(
            model=model,
            tokenizer=tokenizer,
            text=text,
            selected_layers=selected_layers,
            max_length=max_length,
        )
        mean_rows.append(mean_vectors)
        last_rows.append(last_vectors)
        token_counts.append(token_count)
        token_id_hashes.append(token_id_sha256)
        if ordinal == 1 or ordinal % 25 == 0 or ordinal == len(texts):
            print(
                f"[definition-anchor:{progress_prefix}] {ordinal}/{len(texts)} "
                f"tokens={token_count} layers={len(selected_layers)}",
                flush=True,
            )
    return (
        np.stack(mean_rows, axis=0).astype(np.float16),
        np.stack(last_rows, axis=0).astype(np.float16),
        np.asarray(token_counts, dtype=np.int32),
        unicode_array(token_id_hashes),
    )


def capture_single_text_vectors(
    *,
    model: Any,
    tokenizer: Any,
    text: str,
    selected_layers: Sequence[tuple[int, Any]],
    max_length: int,
) -> tuple[np.ndarray, np.ndarray, int, str]:
    # Tokenize without truncation first. Silent truncation changes the definition
    # or evaluation input and is therefore a source-integrity failure.
    inputs = tokenizer(text, return_tensors="pt", truncation=False)
    if "input_ids" not in inputs:
        raise RuntimeError("Tokenizer did not return input_ids")
    token_count = int(inputs["input_ids"].shape[-1])
    if token_count < 1:
        raise RuntimeError("Tokenizer returned an empty sequence")
    enforce_token_limit(token_count, max_length)
    token_id_sha256 = sha256_json(inputs["input_ids"].detach().cpu().tolist())
    device = first_real_parameter_device(model)
    if device is not None:
        inputs = {key: value.to(device) for key, value in inputs.items()}
    attention_mask = inputs.get("attention_mask")
    captures: dict[int, tuple[Any, Any]] = {}
    handles = []
    try:
        for layer_index, block in selected_layers:
            # Deliberately register on the complete block. Do not substitute block.mlp.
            handles.append(
                block.register_forward_hook(
                    _capture_block_mean_and_last(captures, layer_index, attention_mask)
                )
            )
        with inference_context():
            model(**inputs, use_cache=False)
    finally:
        for handle in handles:
            handle.remove()
    missing = [index for index, _block in selected_layers if index not in captures]
    if missing:
        raise RuntimeError(f"Missing complete-block captures for layers: {missing}")
    mean = np.stack(
        [captures[index][0].numpy() for index, _block in selected_layers],
        axis=0,
    )
    last = np.stack(
        [captures[index][1].numpy() for index, _block in selected_layers],
        axis=0,
    )
    return mean, last, token_count, token_id_sha256


def _capture_block_mean_and_last(
    captures: dict[int, tuple[Any, Any]],
    layer_index: int,
    attention_mask: Any,
):
    def hook(_module: Any, _inputs: Any, output: Any) -> None:
        value = output[0] if isinstance(output, (tuple, list)) else output
        if getattr(value, "ndim", None) != 3 or int(value.shape[0]) != 1:
            raise RuntimeError(
                f"Layer {layer_index} block output must be [1, tokens, hidden], got "
                f"{getattr(value, 'shape', None)}"
            )
        sequence_length = int(value.shape[1])
        if attention_mask is None:
            mask = value.new_ones((1, sequence_length))
        else:
            mask = attention_mask[:, :sequence_length].to(device=value.device, dtype=value.dtype)
        weights = mask.unsqueeze(-1)
        denominator = weights.sum(dim=1).clamp_min(1.0)
        mean_vector = (value[:, :sequence_length] * weights).sum(dim=1) / denominator
        valid_positions = mask[0].nonzero(as_tuple=False).flatten()
        if int(valid_positions.numel()) < 1:
            raise RuntimeError(f"Layer {layer_index} has no unmasked tokens")
        last_position = int(valid_positions[-1].item())
        last_vector = value[0, last_position]
        captures[layer_index] = (
            mean_vector[0].detach().float().cpu(),
            last_vector.detach().float().cpu(),
        )

    return hook


