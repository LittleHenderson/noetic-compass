def git_text(arguments: Sequence[str]) -> str | None:
    try:
        completed = subprocess.run(
            ["git", *arguments],
            cwd=REPOSITORY_ROOT,
            check=True,
            capture_output=True,
            text=True,
            timeout=15,
        )
        return completed.stdout.strip() or None
    except Exception:
        return None


def git_lines(arguments: Sequence[str]) -> list[str]:
    text = git_text(arguments)
    return [] if text is None else text.splitlines()


