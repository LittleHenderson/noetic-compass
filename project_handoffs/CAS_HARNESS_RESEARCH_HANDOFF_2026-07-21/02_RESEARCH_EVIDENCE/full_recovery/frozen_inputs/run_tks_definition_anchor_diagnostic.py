def tfidf_anchor_predictions(
    definition_texts: Sequence[str],
    evaluation_texts: Sequence[str],
    labels: Sequence[str],
) -> tuple[np.ndarray, dict[str, Any]]:
    if len(definition_texts) != len(labels):
        raise ValueError("TF-IDF definition count must match label count")
    definition_tokens = [tokenize_surface(text) for text in definition_texts]
    evaluation_tokens = [tokenize_surface(text) for text in evaluation_texts]
    predictions, diagnostics = tfidf_from_tokens(
        definition_tokens, evaluation_tokens, labels
    )
    diagnostics.update(
        {
            "tokenizer": "lowercase regex alphanumeric/apostrophe word tokens",
            "feature_family": "word_unigram",
        }
    )
    return predictions, diagnostics


def char_ngram_tfidf_anchor_predictions(
    definition_texts: Sequence[str],
    evaluation_texts: Sequence[str],
    labels: Sequence[str],
    *,
    minimum_n: int,
    maximum_n: int,
) -> tuple[np.ndarray, dict[str, Any]]:
    if minimum_n < 1 or maximum_n < minimum_n:
        raise ValueError("Invalid character n-gram range")
    definition_tokens = [
        character_ngrams(text, minimum_n=minimum_n, maximum_n=maximum_n)
        for text in definition_texts
    ]
    evaluation_tokens = [
        character_ngrams(text, minimum_n=minimum_n, maximum_n=maximum_n)
        for text in evaluation_texts
    ]
    predictions, diagnostics = tfidf_from_tokens(
        definition_tokens, evaluation_tokens, labels
    )
    diagnostics.update(
        {
            "tokenizer": "lowercase whitespace-normalized character n-grams",
            "feature_family": f"character_{minimum_n}_to_{maximum_n}_grams",
            "minimum_n": minimum_n,
            "maximum_n": maximum_n,
        }
    )
    return predictions, diagnostics


def tfidf_from_tokens(
    definition_tokens: Sequence[Sequence[str]],
    evaluation_tokens: Sequence[Sequence[str]],
    labels: Sequence[str],
) -> tuple[np.ndarray, dict[str, Any]]:
    if len(definition_tokens) != len(labels):
        raise ValueError("TF-IDF definition count must match label count")
    vocabulary = sorted({token for document in definition_tokens for token in document})
    if not vocabulary:
        raise ValueError("TF-IDF definitions produced an empty vocabulary")
    token_index = {token: index for index, token in enumerate(vocabulary)}
    document_frequency = np.zeros(len(vocabulary), dtype=np.float64)
    for tokens in definition_tokens:
        for token in set(tokens):
            document_frequency[token_index[token]] += 1.0
    idf = np.log((1.0 + len(definition_tokens)) / (1.0 + document_frequency)) + 1.0
    definition_matrix = tfidf_matrix(definition_tokens, token_index, idf)
    evaluation_matrix = tfidf_matrix(evaluation_tokens, token_index, idf)
    definition_matrix, definition_zero = l2_normalise_rows_allow_zero(definition_matrix)
    evaluation_matrix, evaluation_zero = l2_normalise_rows_allow_zero(evaluation_matrix)
    similarities = evaluation_matrix @ definition_matrix.T
    winners = np.argmax(similarities, axis=1)
    return np.asarray(labels)[winners], {
        "vocabulary_size": len(vocabulary),
        "zero_definition_vectors": int(np.sum(definition_zero)),
        "zero_evaluation_vectors": int(np.sum(evaluation_zero)),
        "tf": "raw count",
        "idf": "log((1+n_definition_docs)/(1+df))+1",
    }


def tokenize_surface(text: str) -> list[str]:
    return re.findall(r"[a-z0-9]+(?:'[a-z0-9]+)?", str(text).lower())


def character_ngrams(text: str, *, minimum_n: int, maximum_n: int) -> list[str]:
    normalized = re.sub(r"\s+", " ", str(text).lower()).strip()
    return [
        normalized[start : start + width]
        for width in range(minimum_n, maximum_n + 1)
        for start in range(0, max(0, len(normalized) - width + 1))
    ]


def tfidf_matrix(
    documents: Sequence[Sequence[str]],
    token_index: dict[str, int],
    idf: np.ndarray,
) -> np.ndarray:
    matrix = np.zeros((len(documents), len(token_index)), dtype=np.float64)
    for row, tokens in enumerate(documents):
        counts = Counter(token for token in tokens if token in token_index)
        for token, count in counts.items():
            matrix[row, token_index[token]] = float(count) * idf[token_index[token]]
    return matrix


def l2_normalise_rows_allow_zero(values: np.ndarray) -> tuple[np.ndarray, np.ndarray]:
    norms = np.linalg.norm(values, axis=1, keepdims=True)
    zero = norms[:, 0] <= 1e-12
    safe = norms.copy()
    safe[zero] = 1.0
    return values / safe, zero


def validate_resolved_model_revision(
    requested_revision: str,
    resolved_commits: set[str],
    artifact_provenance: dict[str, Any],
) -> None:
    requested = str(requested_revision).strip().lower()
    if not re.fullmatch(r"[0-9a-f]{40}", requested):
        # Explicit canaries are already permanently non-claim and may not expose
        # a resolved commit. Claim-preserving runs never enter this branch.
        return
    if not resolved_commits:
        raise RuntimeError(
            "Transformers did not report a resolved model commit hash; exact revision binding "
            "cannot be proven."
        )
    if requested not in resolved_commits:
        raise RuntimeError(
            f"Requested model revision {requested} is absent from Transformers-resolved commits "
            f"{sorted(resolved_commits)}"
        )
    mismatched = sorted(value for value in resolved_commits if value != requested)
    if mismatched:
        raise RuntimeError(
            f"Transformers resolved artifacts from commits other than {requested}: {mismatched}"
        )
    snapshot_commits = set(artifact_provenance.get("snapshot_commits", []))
    if snapshot_commits and requested not in snapshot_commits:
        raise RuntimeError(
            f"Cached artifact paths do not include the requested snapshot {requested}: "
            f"{sorted(snapshot_commits)}"
        )


def resolve_hf_artifact_provenance(
    model_id: str,
    revision: str,
    *,
    trust_remote_code: bool,
) -> dict[str, Any]:
    try:
        from transformers.utils.hub import cached_file
    except Exception as exc:
        return {
            "artifacts": [],
            "snapshot_commits": [],
            "inspection_error": f"{type(exc).__name__}: {exc}",
        }
    candidate_names = [
        "config.json",
        "generation_config.json",
        "tokenizer_config.json",
        "tokenizer.json",
        "tokenizer.model",
        "spiece.model",
        "vocab.json",
        "merges.txt",
        "added_tokens.json",
        "special_tokens_map.json",
        "model.safetensors.index.json",
        "model.safetensors",
        "pytorch_model.bin.index.json",
        "pytorch_model.bin",
    ]
    paths: list[Path] = []
    errors: list[str] = []
    for filename in candidate_names:
        try:
            cached = cached_file(
                model_id,
                filename,
                revision=revision,
                local_files_only=True,
                trust_remote_code=trust_remote_code,
                _raise_exceptions_for_missing_entries=False,
            )
        except TypeError:
            try:
                cached = cached_file(
                    model_id,
                    filename,
                    revision=revision,
                    local_files_only=True,
                )
            except Exception:
                cached = None
        except Exception as exc:
            errors.append(f"{filename}: {type(exc).__name__}: {exc}")
            cached = None
        if cached:
            path = Path(cached)
            paths.append(path)
            if filename.endswith(".index.json"):
                try:
                    index_payload = json.loads(path.read_text(encoding="utf-8"))
                    weight_map = index_payload.get("weight_map", {})
                    if isinstance(weight_map, dict):
                        for shard in sorted(set(str(value) for value in weight_map.values())):
                            shard_path = path.parent / shard
                            if shard_path.exists():
                                paths.append(shard_path)
                except Exception as exc:
                    errors.append(f"{filename} shard map: {type(exc).__name__}: {exc}")
    deduplicated: list[Path] = []
    seen: set[str] = set()
    for path in paths:
        key = str(path)
        if key not in seen:
            seen.add(key)
            deduplicated.append(path)
    artifacts = [hf_artifact_entry(path) for path in deduplicated]
    snapshot_commits = sorted(
        {
            match.group(1).lower()
            for path in deduplicated
            for match in [re.search(r"[\\/]snapshots[\\/]([0-9a-fA-F]{40})[\\/]", str(path))]
            if match
        }
    )
    return {
        "artifacts": artifacts,
        "snapshot_commits": snapshot_commits,
        "inspection_errors": errors,
        "artifact_hash_policy": "SHA-256 every resolved file by bounded-memory streaming",
    }


def hf_artifact_entry(path: Path) -> dict[str, Any]:
    size = path.stat().st_size
    entry: dict[str, Any] = {
        "cache_path": str(path),
        "resolved_path": str(path.resolve()),
        "filename": path.name,
        "bytes": size,
    }
    entry["sha256"] = sha256_file(path)
    return entry


