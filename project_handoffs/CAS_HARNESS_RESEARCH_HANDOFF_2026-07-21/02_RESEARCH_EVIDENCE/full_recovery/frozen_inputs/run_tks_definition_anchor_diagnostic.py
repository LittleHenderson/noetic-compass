def read_json(path: Path) -> dict[str, Any]:
    try:
        payload = json.loads(path.read_text(encoding="utf-8"))
    except FileNotFoundError as exc:
        raise ValueError(f"Required source file does not exist: {path}") from exc
    if not isinstance(payload, dict):
        raise ValueError(f"Expected a JSON object in {path}")
    return payload


def normalise_sha256(value: Any) -> str:
    text = str(value or "").strip().lower()
    if not re.fullmatch(r"[0-9a-f]{64}", text):
        raise ValueError(f"Expected an exact SHA-256 hex digest, got {value!r}")
    return text


def sha256_file(path: Path) -> str:
    digest = hashlib.sha256()
    try:
        with path.open("rb") as handle:
            for chunk in iter(lambda: handle.read(1024 * 1024), b""):
                digest.update(chunk)
    except FileNotFoundError as exc:
        raise ValueError(f"Required source file does not exist: {path}") from exc
    return digest.hexdigest()


def sha256_json(value: Any) -> str:
    encoded = json.dumps(value, sort_keys=True, separators=(",", ":"), ensure_ascii=False).encode(
        "utf-8"
    )
    return hashlib.sha256(encoded).hexdigest()


def sha256_definition_records(records: Sequence[DefinitionRecord]) -> str:
    return sha256_json(
        [
            {
                "label": record.label,
                "legacy_code": record.legacy_code,
                "title": record.title,
                "definition": record.definition,
                "prototype_text": record.prototype_text,
            }
            for record in records
        ]
    )


def unicode_array(values: Iterable[Any]) -> np.ndarray:
    return np.asarray([str(value) for value in values], dtype=np.str_)


def stable_seed(seed: int, *parts: Any) -> int:
    material = "|".join([str(seed), *(str(part) for part in parts)]).encode("utf-8")
    return int.from_bytes(hashlib.sha256(material).digest()[:8], "big", signed=False)


