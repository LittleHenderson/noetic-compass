def verify_raw_diagnostic_artifact(
    path: Path,
    *,
    expected_eval_shape: Sequence[int],
    expected_definition_shape: Sequence[int],
    expected_scenario_count: int,
    expected_arm_count: int,
) -> dict[str, Any]:
    required = {
        "schema_version",
        "provenance_json",
        "layers",
        "eval_mean",
        "eval_last",
        "eval_token_counts",
        "eval_token_id_sha256",
        "scenario_ids",
        "scenario_prompts",
        "scenario_foundations",
        "scenario_splits",
        "scenario_group_ids",
        "arm_names",
        "arm_source_sha256",
        "definition_labels",
        "definition_texts",
        "definition_mean",
        "definition_last",
        "definition_token_counts",
        "definition_token_id_sha256",
    }
    sha256_before = sha256_file(path)
    with np.load(path, allow_pickle=False) as payload:
        missing = sorted(required - set(payload.files))
        if missing:
            raise RuntimeError(f"Raw diagnostic artifact is missing fields: {missing}")
        if str(payload["schema_version"][0]) != RAW_SCHEMA:
            raise RuntimeError("Raw diagnostic artifact schema mismatch")
        if tuple(payload["eval_mean"].shape) != tuple(expected_eval_shape):
            raise RuntimeError("Raw diagnostic eval_mean shape mismatch")
        if tuple(payload["eval_last"].shape) != tuple(expected_eval_shape):
            raise RuntimeError("Raw diagnostic eval_last shape mismatch")
        if tuple(payload["definition_mean"].shape) != tuple(expected_definition_shape):
            raise RuntimeError("Raw diagnostic definition_mean shape mismatch")
        if tuple(payload["definition_last"].shape) != tuple(expected_definition_shape):
            raise RuntimeError("Raw diagnostic definition_last shape mismatch")
        if len(payload["scenario_ids"]) != expected_scenario_count:
            raise RuntimeError("Raw diagnostic scenario count mismatch")
        if len(payload["arm_names"]) != expected_arm_count:
            raise RuntimeError("Raw diagnostic arm count mismatch")
        token_hashes = np.concatenate(
            [
                payload["eval_token_id_sha256"].reshape(-1),
                payload["definition_token_id_sha256"].reshape(-1),
            ]
        )
        if any(not re.fullmatch(r"[0-9a-f]{64}", str(value)) for value in token_hashes):
            raise RuntimeError("Raw diagnostic artifact contains an invalid token-ID hash")
    sha256_after = sha256_file(path)
    if sha256_before != sha256_after:
        raise RuntimeError("Raw diagnostic artifact changed during reopen verification")
    return {
        "status": "LOCAL_DIAGNOSTIC_ARTIFACT_ATOMIC_WRITE_REOPEN_VERIFIED",
        "sha256": sha256_after,
        "bytes": path.stat().st_size,
        "allow_pickle": False,
        "required_field_count": len(required),
        "eval_shape": list(expected_eval_shape),
        "definition_shape": list(expected_definition_shape),
    }


def build_token_length_summary(
    eval_token_counts: np.ndarray,
    definition_token_counts: np.ndarray,
    *,
    scenarios: Sequence[EvalScenario],
    arms: Sequence[DefinitionArm],
) -> dict[str, Any]:
    split_summaries = {}
    for split in sorted({scenario.split for scenario in scenarios}):
        mask = np.asarray([scenario.split == split for scenario in scenarios], dtype=bool)
        split_summaries[split] = numeric_summary(eval_token_counts[mask])
    arm_summaries = {
        arm.name: numeric_summary(definition_token_counts[index])
        for index, arm in enumerate(arms)
    }
    return {
        "evaluation_all": numeric_summary(eval_token_counts),
        "evaluation_by_split": split_summaries,
        "definitions_by_arm": arm_summaries,
    }


def numeric_summary(values: np.ndarray) -> dict[str, Any]:
    array = np.asarray(values, dtype=np.float64)
    if array.size < 1:
        raise ValueError("Cannot summarize an empty numeric array")
    return {
        "n": int(array.size),
        "minimum": float(np.min(array)),
        "median": float(np.median(array)),
        "mean": float(np.mean(array)),
        "maximum": float(np.max(array)),
    }


