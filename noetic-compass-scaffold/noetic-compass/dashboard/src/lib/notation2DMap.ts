import canonicalLayout from '../../../research/cas_probe/stage23_a_notation_2d_layout.json';

// ── Types ─────────────────────────────────────────────────────────────

/**
 * String-literal union mirroring the Python `PrimitiveKind` Literal in
 * `cas-native/atlas/notation_2d_map.py`. Order matches the Python source
 * for review symmetry.
 */
export type PrimitiveKind =
  // Stage 23.A
  | 'noetic'
  | 'domain'
  | 'drive'
  | 'register'
  | 'cognitive_state'
  // Stage 23.A.2
  | 'operation'
  | 'inversion_axis'
  | 'foundation'
  | 'production'
  | 'rpm_pathway'
  | 'set_constructor'
  | 'set_relation'
  | 'set_operation'
  | 'combinator'
  | 'authority_set'
  | 'cardinality_kind'
  // Stage 23.A.3
  | 'emergent_omega';

/** Canonical 2D coordinate for a single CAS primitive. */
export interface Position2D {
  primitive: string;
  kind: PrimitiveKind;
  x: number;
  y: number;
}

/**
 * A single CAS-expression detection rule. Stage 23.A.1.2: detection priority
 * is data-driven from `payload.detection_rules`, replacing the hardcoded TS
 * regex sequence. Agent A's Python source builds these rules in canonical
 * priority order (lowest priority number = highest matching specificity).
 */
export interface DetectionRule {
  priority: number;
  kind: PrimitiveKind;
  /** A JavaScript-compatible regex string (consumed via `new RegExp(...)`). */
  regex: string;
  description: string;
}

/** Top-level JSON payload shape committed at
 * `research/cas_probe/stage23_a_notation_2d_layout.json`. */
export interface CanonicalLayoutPayload {
  boundary?: string;
  layout_version: string;
  scope?: string;
  primitives: Position2D[];
  /**
   * Stage 23.A.1.2: priority-ordered CAS-expression detection rules,
   * shared with the Python adapter. Optional for backward compatibility:
   * if absent, the TS adapter falls back to a hardcoded regex sequence
   * that produces the same result for the same input. The fallback path
   * is removed once every consumer has migrated to a JSON with this field.
   */
  detection_rules?: DetectionRule[];
}

// ── Internal state ────────────────────────────────────────────────────

const payload = canonicalLayout as CanonicalLayoutPayload;

// Build a primitive → Position2D index once at load time. The JSON is the
// canonical source of truth; we do NOT regenerate geometry on the TS side.
const positionIndex: Map<string, Position2D> = new Map();
for (const p of payload.primitives) {
  positionIndex.set(p.primitive, p);
}

// ── Public API ────────────────────────────────────────────────────────

/**
 * Single-primitive lookup. Returns the canonical 2D position for a CAS
 * primitive, or `null` if the primitive is not in the canonical map.
 *
 * Bare `'E'` is REJECTED with a clear error — same discipline as the
 * Python `get_position`. Use `'^E'` for the Evaluative Domain or
 * `'|E'` for the Embodied Register.
 *
 * @throws Error when called with bare ambiguous `'E'`.
 */
export function getPosition2D(primitive: string): Position2D | null {
  if (primitive === 'E') {
    throw new Error(
      "'E' is ambiguous: use '^E' for the Evaluative Domain or " +
        "'|E' for the Embodied Register."
    );
  }
  const hit = positionIndex.get(primitive);
  return hit ?? null;
}

/**
 * Full canonical layout — every primitive the canonical JSON covers,
 * in the order the JSON serializes them. Count is determined by the
 * JSON file, not hardcoded.
 */
export function allPositions(): Position2D[] {
  // Return a shallow copy so callers can't mutate the cached index.
  return payload.primitives.slice();
}

/**
 * The `layout_version` field of the canonical JSON. Renderers and
 * downstream consumers should check this value to detect layout
 * regenerations.
 */
export function layoutVersion(): string {
  return payload.layout_version;
}

/**
 * The raw payload, exposed for tests and tooling that need to inspect
 * the canonical JSON shape (e.g. count-agnostic assertions). Returns
 * the live module-level object; consumers MUST treat it as read-only.
 */
export function _canonicalPayload(): CanonicalLayoutPayload {
  return payload;
}

