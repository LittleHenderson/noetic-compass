SLOTS = {
    "name": ["stonewick", "ivybridge", "oakridge", "oxley", "glenhollow", "vellmoor"],
    "thing": ["colonies", "hives", "samples", "crates", "barrels"],
    "month": ["september", "october", "november", "april", "january", "december"],
    "place": ["yard", "depot", "store", "field", "shed"],
    "num": ["eight", "fourteen", "five", "nine", "seventeen", "twelve"],
    "num2": ["twelve", "three", "six", "ten", "two"],
}


def fill(text: str, rng) -> str:
    out = text
    for k, vals in SLOTS.items():
        while "{%s}" % k in out:
            out = out.replace("{%s}" % k, rng.choice(vals), 1)
    return out
