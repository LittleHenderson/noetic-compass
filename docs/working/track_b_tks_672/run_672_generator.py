"""TRACK_B_TKS_672_CORPUS — generator + June-gate admission lock.

A LOCK. Freezes the generator, binds the June 2026 surface gates by hash, and
emits the three separate manifests. Running it produces the corpus; nothing here
scores a small model.

ADMISSION ORDER (gates run DURING admission, never as a post-hoc audit):
  structured plan -> three sibling drafts -> direct-label prohibition
  -> answer stripping -> June surface gates -> independent recoverability judge
  -> freeze

A rejected scenario is NEVER repaired using the judge's predicted label. That
would make the judge a co-author and fit the corpus to its own evaluator.
Retries are counted and reported; they are not hidden.

FIREWALL: this track reads no Phase A result and does not choose any layer,
hook, position, or direction. Canonical sources are read-only.

CANON: 28 Foundations 1.0. No renaming, remapping, or semantic replacement.
Agency / Structure / Purpose are positional relabels and are NOT used here.
"""
from __future__ import annotations

import hashlib
import json
import os
import re
import sys
import time
from pathlib import Path

HERE = Path(__file__).resolve().parent
REPO = HERE.parents[2]
JUNE = REPO / "docs" / "working" / "mtc_f28_goemotions_20260615"
CANON = REPO / "docs/working/gate2_closure/matched_ab_20260726/tootra_28_full_definitions.json"
SPEC = REPO / "docs/working/gate2_closure/matched_ab_20260726/owner_scenario_spec.md"
sys.path.insert(0, str(JUNE))

AUTHOR_MODEL = "models/gemini-2.5-flash-lite"
JUDGE_MODEL = "models/gemini-2.5-flash"
TEMPERATURE = 0.95
TOP_P = 0.95
RETRY_LIMIT = 2                 # transport errors only, never quality
N_PLANS = 8                     # 8 INDEPENDENT plans per Foundation
N_SIBLINGS = 3
SURFACE_THRESHOLD = 0.60        # June gate, NOT re-chosen here
LENGTH_RANGE = (80, 160)
WORLDS = {"a": "Spiritual", "b": "Mental", "c": "Emotional", "d": "Physical"}

# Direct World-label prohibition. June already established Register/World is the
# surface-loud axis; the 56% leak in the 84-item run was a REDISCOVERY of it.
PROHIBITED = re.compile(
    r"\b(spiritual(ly)?|mental(ly)?|emotional(ly)?|physical(ly)?)\b", re.I)

# Boundary stress families, reserved per the Foundation 4 / 6 diagnostics.
BOUNDARY_RUBRIC = {
    "4a": "bond located in a spiritual ontology - soul lineage, nonphysical communion, "
          "mystical order, ancestor/entity relation, dissolution of metaphysical separation",
    "4c": "outcome is an affective bond - felt intimacy, vulnerability, affection, "
          "emotional safety, acceptance, shared feeling",
    "6a": "spiritual sustenance or sacred/etheric resource",
    "6b": "mental content, doctrine, thought-form, model, intellectual property",
    "6c": "feeling or comfort mediated by an object or possession",
    "6d": "tangible possession, food, consumption, property, material resource",
}


def sha_file(p: Path) -> str:
    return hashlib.sha256(p.read_bytes()).hexdigest()


def sha_str(s: str) -> str:
    return hashlib.sha256(s.encode("utf-8")).hexdigest()


def load_canon():
    d = json.loads(CANON.read_text(encoding="utf-8"))
    return d["definitions"], d["drive_map"], d["world_map"]


def write_manifests(defs, drives, worlds):
    """Three PHYSICALLY SEPARATE manifests. Shared position never implies shared meaning."""
    (HERE / "TKS_28_FOUNDATION_BENCHMARK.json").write_text(json.dumps({
        "manifest": "TKS_28_FOUNDATION_BENCHMARK",
        "authority": "28 Foundations 1.0",
        "authority_sha256": sha_file(CANON),
        "labels": sorted(defs), "worlds": worlds, "drives": drives,
        "rule": "governed EXCLUSIVELY by the canonical 28 Foundations; no CAS drive names",
    }, indent=2, sort_keys=True), encoding="utf-8")

    (HERE / "CAS_NATIVE_CIRCUIT_BENCHMARK.json").write_text(json.dumps({
        "manifest": "CAS_NATIVE_CIRCUIT_BENCHMARK",
        "authority": "CAS PCBA / CAS specification",
        "drives": ["F1 Unity", "F2 Wisdom", "F3 Vitality", "F4 Connection",
                   "F5 Agency", "F6 Structure", "F7 Purpose"],
        "coordinates": ["Noetic ^0-^9", "Domain P/C/E/O", "Register T/A/f/E"],
        "rule": "native CAS grammar; NOT automatic substitutes for canonical TKS drives",
        "status": "no items generated by this track",
    }, indent=2, sort_keys=True), encoding="utf-8")

    (HERE / "TKS_TO_CAS_TRANSLATION_EXPERIMENT.json").write_text(json.dumps({
        "manifest": "TKS_TO_CAS_TRANSLATION_EXPERIMENT",
        "status": "HYPOTHESES ONLY - NOT TESTED, NOT LICENSED",
        "rule": "the ONLY place cross-system correspondence may be proposed or tested",
        "hard_rule": "shared grid position NEVER implies shared meaning",
        "correspondence_hypotheses": [
            {"tks": "5 worldly power, influence, control", "cas": "F5 Agency",
             "evidence_status": "UNTESTED",
             "falsification": "if power-over and self-direction dissociate behaviourally, reject"},
            {"tks": "6 material food and things", "cas": "F6 Structure",
             "evidence_status": "UNTESTED",
             "falsification": "if possession/consumption and ordering dissociate, reject"},
            {"tks": "7 lust, sex, reproduction", "cas": "F7 Purpose",
             "evidence_status": "UNTESTED",
             "falsification": "if replication and aim-orientation dissociate, reject"},
        ],
        "prior_failure": "conflating these voided SMALL-MODEL-SEMANTIC-MATCH-v1 (cb0eaffd)",
    }, indent=2, sort_keys=True), encoding="utf-8")
    print("WROTE three separate manifests")


def frozen_config(spec_text, author_tmpl):
    return {
        "track": "TRACK_B_TKS_672_CORPUS",
        "author_model": AUTHOR_MODEL, "judge_model": JUDGE_MODEL,
        "temperature": TEMPERATURE, "top_p": TOP_P,
        "author_prompt_hash": sha_str(author_tmpl + spec_text),
        "spec_sha256": sha_file(SPEC), "canon_sha256": sha_file(CANON),
        "june_gate_sha256": sha_file(JUNE / "surface_gate_f28_goemotions.py"),
        "june_judge_sha256": sha_file(JUNE / "gate2_confirmatory_tks_original_blind.py"),
        "surface_threshold": SURFACE_THRESHOLD,
        "surface_threshold_source": "June 2026 gate, NOT re-chosen after generation",
        "n_plans": N_PLANS, "n_siblings": N_SIBLINGS, "target_items": 28 * N_PLANS * N_SIBLINGS,
        "retry_limit": RETRY_LIMIT, "retry_policy": "transport errors ONLY, never quality",
        "length_range": list(LENGTH_RANGE),
        "prohibited_expressions": PROHIBITED.pattern,
        "rejection_rules": ["direct World label", "length outside range", "code leak",
                            "terminology leak", "surface gate above threshold"],
        "judge_repair_policy": "PROHIBITED - a rejected item is never repaired using the "
                              "judge's predicted label; that makes the judge a co-author",
        "seed_policy": "seed = 20260727 + plan_index, recorded per item",
        "firewall": "reads no Phase A result; selects no layer, hook, position or direction",
    }


AUTHOR_TMPL = """{spec}

---

CANONICAL TARGET (28 Foundations 1.0 - authoritative, do not substitute):
  code   {code}
  World  {world}
  Drive  {drive}
  Full definition: {definition}
{boundary}
Build ONE structured plan, then write {n} sibling vignettes from THAT SINGLE plan.
This is plan family {plan_idx} of {n_plans}; it must be INDEPENDENT of the other
plan families for this code - differing in actor, setting, stakes, conflict,
causal structure, decision and outcome. It must NOT be a paraphrase of another story.

ABSOLUTE PROHIBITION: the words spiritual, mental, emotional, physical (and their
adverb forms) must NOT appear. Encode the World behaviourally instead. This is the
known surface-loud axis and items containing those words are rejected outright.

Return ONLY JSON:
{{"plan":{{"actor":"...","setting":"...","stakes":"...","conflict":"...",
  "causal_structure":"...","decision":"...","outcome":"..."}},
  "siblings":[{{"sibling_role":"s1","scenario":"..."}}]}}

Each scenario is {lo}-{hi} words of naturalistic prose. No foundation code, no
Tootra terminology, no copied definition wording."""


def main() -> int:
    import google.generativeai as genai
    import surface_gate_f28_goemotions as june_gate   # hash-bound above

    key = os.environ.get("GEMINI_API_KEY") or os.environ.get("GOOGLE_API_KEY")
    if not key:
        raise SystemExit("GEMINI_API_KEY or GOOGLE_API_KEY required")
    genai.configure(api_key=key)

    defs, drives, worlds = load_canon()
    spec = SPEC.read_text(encoding="utf-8")
    write_manifests(defs, drives, worlds)
    cfg = frozen_config(spec, AUTHOR_TMPL)
    (HERE / "frozen_config.json").write_text(json.dumps(cfg, indent=2, sort_keys=True),
                                             encoding="utf-8")
    print("FROZEN CONFIG")
    for k in ("june_gate_sha256", "surface_threshold", "target_items", "author_prompt_hash"):
        print(f"   {k}: {cfg[k]}")
    print(f"   june gate THRESHOLD in code: {june_gate.THRESHOLD}")
    if june_gate.THRESHOLD != SURFACE_THRESHOLD:
        raise SystemExit(f"June gate threshold drift: {june_gate.THRESHOLD} != {SURFACE_THRESHOLD}")

    records = []
    path = HERE / "corpus_records.json"
    if path.exists():
        records = json.loads(path.read_text(encoding="utf-8"))
    done = {(r["foundation_code"], r["plan_family_id"]) for r in records}
    model = genai.GenerativeModel(AUTHOR_MODEL)

    for code in sorted(defs):
        for plan_idx in range(N_PLANS):
            if (code, plan_idx) in done:
                continue
            boundary = (f"\nBOUNDARY RUBRIC for this code (operational, does NOT rewrite canon):\n"
                        f"  {BOUNDARY_RUBRIC[code]}\n") if code in BOUNDARY_RUBRIC else ""
            prompt = AUTHOR_TMPL.format(
                spec=spec, code=code, world=worlds[code[1]], drive=drives[code[0]],
                definition=defs[code], boundary=boundary, n=N_SIBLINGS,
                plan_idx=plan_idx, n_plans=N_PLANS, lo=LENGTH_RANGE[0], hi=LENGTH_RANGE[1])
            seed = 20260727 + plan_idx
            got, retries, last = None, 0, ""
            for attempt in range(1, RETRY_LIMIT + 2):
                try:
                    resp = model.generate_content(
                        prompt, generation_config={"temperature": TEMPERATURE, "top_p": TOP_P,
                                                   "max_output_tokens": 8192,
                                                   "response_mime_type": "application/json"},
                        request_options={"timeout": 180})
                    got = json.loads(resp.text)
                    break
                except Exception as exc:  # noqa: BLE001 — transport only
                    last = f"{type(exc).__name__}"
                    retries += 1
                    time.sleep(2 * attempt)
            if not got or not got.get("siblings"):
                records.append({"foundation_code": code, "plan_family_id": plan_idx,
                                "sibling_role": None, "author_seed": seed,
                                "retry_count": retries, "accepted": False,
                                "rejection_reason": f"generation_failed:{last}"})
                path.write_text(json.dumps(records, indent=1), encoding="utf-8")
                continue

            for sib in got["siblings"][:N_SIBLINGS]:
                text = str(sib.get("scenario", "")).strip()
                n_words = len(text.split())
                reason = None
                leak = PROHIBITED.findall(text)
                if leak:
                    reason = f"direct_world_label:{sorted({l[0].lower() for l in leak})}"
                elif not (LENGTH_RANGE[0] - 20 <= n_words <= LENGTH_RANGE[1] + 40):
                    reason = f"length_{n_words}"
                elif re.search(rf"\b{re.escape(code)}\b", text, re.I):
                    reason = "code_leak"
                elif re.search(r"\bTootra\b|\bFoundation\b", text):
                    reason = "terminology_leak"
                records.append({
                    "foundation_code": code, "plan_family_id": plan_idx,
                    "sibling_role": sib.get("sibling_role"), "author_seed": seed,
                    "first_pass_text": text, "final_text": None if reason else text,
                    "n_words": n_words, "retry_count": retries,
                    "accepted": not reason, "rejection_reason": reason,
                    "plan": got.get("plan"),
                    "author_prompt_hash": cfg["author_prompt_hash"],
                    "author_model": AUTHOR_MODEL,
                })
            path.write_text(json.dumps(records, indent=1), encoding="utf-8")
            acc = sum(1 for r in records if r.get("accepted"))
            print(f"  {code} plan {plan_idx}: {acc} accepted so far", flush=True)

    # ---- authoring yield, always reported; never just the surviving 672
    total = len([r for r in records if r.get("sibling_role")])
    acc = [r for r in records if r.get("accepted")]
    rej = [r for r in records if r.get("sibling_role") and not r.get("accepted")]
    from collections import Counter
    causes = Counter((r.get("rejection_reason") or "").split(":")[0] for r in rej)
    world_leak = sum(1 for r in rej if str(r.get("rejection_reason", "")).startswith("direct_world"))
    yield_report = {
        "generated_siblings": total, "accepted": len(acc), "rejected": len(rej),
        "first_pass_acceptance_rate": round(len(acc) / total, 4) if total else 0.0,
        "mean_retries": round(sum(r.get("retry_count", 0) for r in records) / max(1, len(records)), 3),
        "rejections_by_cause": dict(causes),
        "world_register_leak_rejection_rate": round(world_leak / total, 4) if total else 0.0,
        "note": "reported BEFORE any small-model readout; the surviving corpus is never "
                "reported alone",
    }
    (HERE / "authoring_yield.json").write_text(json.dumps(yield_report, indent=2, sort_keys=True),
                                               encoding="utf-8")
    print("\nAUTHORING YIELD")
    for k, v in yield_report.items():
        print(f"   {k}: {v}")
    print("\nNEXT: run the June surface gates and the independent recoverability judge, "
          "then freeze CORPUS_TKS_672_FROZEN_MANIFEST. Do NOT run any readout before that.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
