"""WORLD_REALIZATION_GRAMMAR_V1_PILOT — quarantined, 320 candidates.

Tests whether a realization GRAMMAR (causal criteria) reduces direct World-label
leakage where a stated prohibition did not, WITHOUT becoming a synonym whitelist.

FROZEN CONTROL SET — owner-specified, listed directly, never generated by a rule.
A mechanical inability to generate any of these 16 cells STOPS the pilot and
requires a successor lock. No control is replaced after results appear.

QUARANTINE: no item produced here may ever enter TKS_672_V3.
"""
from __future__ import annotations

import hashlib
import json
import os
import re
import sys
import time
from pathlib import Path

HERE = Path(__file__).resolve().parent
REPO = HERE.parents[2]
CANON = REPO / "docs/working/gate2_closure/matched_ab_20260726/tootra_28_full_definitions.json"
SPEC = REPO / "docs/working/gate2_closure/matched_ab_20260726/owner_scenario_spec.md"

AUTHOR_MODEL = "models/gemini-2.5-flash-lite"      # the weak author, unchanged
N_PLANS, N_CANDIDATES = 4, 5
TRANSPORT_RETRIES = 2
PROHIBITED = re.compile(r"\b(spiritual(ly)?|mental(ly)?|emotional(ly)?|physical(ly)?)\b", re.I)

# FROZEN — owner-specified pairs. Order preserved exactly as given.
PAIRS = [("1d", "1b"), ("2a", "2b"), ("5d", "5b"), ("6a", "6c"),
         ("6b", "6d"), ("7a", "7b"), ("7c", "2c"), ("7d", "3d")]
STARVED = [p[0] for p in PAIRS]
CONTROLS = [p[1] for p in PAIRS]
CELLS = STARVED + CONTROLS

# WORLD_REALIZATION_GRAMMAR_V1 — causal criteria, NOT vocabulary.
GRAMMAR = {
    "a": ("SPIRITUAL", "the decisive motive, authority, relationship, or success condition "
          "exists BEYOND an ordinary material, informational, or felt outcome",
          ["nonphysical relationship", "sacred obligation", "continuity beyond bodily presence",
           "metaphysical belonging", "ritual participation", "communion with an unseen order",
           "transformation of existential relation"]),
    "b": ("MENTAL", "the decisive change occurs in a REPRESENTATION",
          ["map", "distinction", "inference", "explanation", "interpretation", "plan",
           "conceptual organization", "understanding"]),
    "c": ("EMOTIONAL", "the decisive change occurs in EXPERIENCED VALUE OR RELATION",
          ["felt attachment", "comfort", "grief", "affection", "aversion", "emotional safety",
           "resentment", "trust", "felt belonging"]),
    "d": ("PHYSICAL", "the decisive change occurs in BODILY, SPATIAL, MATERIAL or OPERATIONAL "
          "reality",
          ["body state", "object possession", "location", "movement", "consumption",
           "construction", "measurable physical condition", "material resource", "direct action"]),
}
# FROZEN train/test split of realization families — the protection against C
# becoming a synonym instrument. Set BEFORE generation.
HELDOUT = {"a": ["continuity beyond bodily presence", "transformation of existential relation"],
           "b": ["conceptual organization", "interpretation"],
           "c": ["felt belonging", "resentment"],
           "d": ["construction", "measurable physical condition"]}

TMPL = """{spec}

---

CANONICAL TARGET (28 Foundations 1.0):
  code {code} | Drive {drive}
  Full definition: {definition}

WORLD REALIZATION GRAMMAR — this is a CAUSAL criterion, not a word list.
  {wname}: {wcrit}

  The governing question for this scenario:
      WHERE MUST THE DECISIVE SUCCESS CRITERION BECOME TRUE?
  For this target it must become true in the {wname} sense above.

  Realization families available for this plan (pick ONE and build the causal
  spine around it; these name FUNCTIONS, not required words):
{families}

ABSOLUTE PROHIBITION — none of these may appear anywhere:
    spiritual  spiritually  mental  mentally  emotional  emotionally
    physical   physically
Realize the World through the causal criterion above instead of naming it.

MANDATORY SELF-CHECK before returning: re-read all {ncand} scenarios and verify none
contains a prohibited word. Rewrite any that does.

Plan family {plan_idx} of {nplans} — INDEPENDENT of the others for this code.

Return ONLY JSON:
{{"realization_family":"<the family you chose>",
  "plan":{{"actor":"...","setting":"...","stakes":"...","decisive_success_criterion":"..."}},
  "candidates":[{{"candidate_index":1,"scenario":"..."}}]}}

Exactly {ncand} candidates, 80-160 words each, naturalistic prose. No foundation code,
no Tootra terminology, no copied definition wording."""


def normalize_payload(obj):
    """APPARATUS REPAIR 2026-07-27: the author returns the scenario list in several
    shapes — a wrapped dict, a bare list, or a dict keyed differently. Normalize to
    {"candidates": [...], "realization_family": ...} without altering any content.
    This touches parsing ONLY. No threshold, control, criterion or prompt changes.
    """
    if isinstance(obj, list):
        return {"candidates": obj, "realization_family": None}
    if not isinstance(obj, dict):
        return {"candidates": []}
    if isinstance(obj.get("candidates"), list):
        return obj
    for k in ("scenarios", "items", "siblings", "results", "data"):
        if isinstance(obj.get(k), list):
            return {**obj, "candidates": obj[k]}
    # a single scenario returned unwrapped
    if isinstance(obj.get("scenario"), str):
        return {**obj, "candidates": [obj]}
    for v in obj.values():                     # last resort: the only list of dicts
        if isinstance(v, list) and v and isinstance(v[0], dict) and "scenario" in v[0]:
            return {**obj, "candidates": v}
    return {**obj, "candidates": []}


def main() -> int:
    import google.generativeai as genai

    key = os.environ.get("GEMINI_API_KEY") or os.environ.get("GOOGLE_API_KEY")
    if not key:
        raise SystemExit("GEMINI_API_KEY or GOOGLE_API_KEY required")
    genai.configure(api_key=key)
    canon = json.loads(CANON.read_text(encoding="utf-8"))
    defs, drives = canon["definitions"], canon["drive_map"]
    spec = SPEC.read_text(encoding="utf-8")

    missing = [c for c in CELLS if c not in defs]
    if missing:
        raise SystemExit(f"STOP: frozen control cells absent from canon: {missing} — successor lock required")

    cfg = {
        "design": "WORLD_REALIZATION_GRAMMAR_V1_PILOT", "quarantined": True,
        "quarantine_rule": "no item here may enter TKS_672_V3",
        "frozen_pairs": PAIRS, "starved": STARVED, "controls": CONTROLS,
        "control_selection": "OWNER-SPECIFIED, listed directly; no rule, no replacement",
        "author_model": AUTHOR_MODEL, "n_plans": N_PLANS, "n_candidates": N_CANDIDATES,
        "grammar_version": "WORLD_REALIZATION_GRAMMAR_V1",
        "heldout_realization_families": HELDOUT,
        "heldout_rationale": "R4/R5 — a character model may learn one family's vocabulary; it "
                             "should NOT transfer to held-out families unless a broader shortcut "
                             "survives. Split frozen BEFORE generation.",
        "v2_baseline_leak": {"5d": 0.350, "7c": 0.375, "6a": 0.300, "7a": 0.300, "1d": 0.275,
                             "overall": 0.142},
        "prompt_hash": hashlib.sha256((TMPL + spec).encode()).hexdigest()[:32],
    }
    (HERE / "pilot_frozen_config.json").write_text(json.dumps(cfg, indent=2, sort_keys=True),
                                                   encoding="utf-8")
    print("WORLD_REALIZATION_GRAMMAR_V1_PILOT  (QUARANTINED)")
    print(f"  16 cells: starved {STARVED}")
    print(f"            controls {CONTROLS}")
    print(f"  {N_PLANS} plans x {N_CANDIDATES} candidates = {len(CELLS)*N_PLANS*N_CANDIDATES}\n")

    model = genai.GenerativeModel(AUTHOR_MODEL)
    path = HERE / "pilot_records.json"
    rec = json.loads(path.read_text(encoding="utf-8")) if path.exists() else []
    done = {(r["code"], r["plan_idx"]) for r in rec}

    for code in CELLS:
        w = code[1]
        wname, wcrit, fams = GRAMMAR[w]
        train_fams = [f for f in fams if f not in HELDOUT[w]]
        for plan_idx in range(N_PLANS):
            if (code, plan_idx) in done:
                continue
            # plans draw only from TRAIN families; held-out families are reserved
            avail = train_fams
            prompt = TMPL.format(
                spec=spec, code=code, drive=drives[code[0]], definition=defs[code],
                wname=wname, wcrit=wcrit,
                families="\n".join(f"      - {f}" for f in avail),
                ncand=N_CANDIDATES, plan_idx=plan_idx, nplans=N_PLANS)
            got, retries, last = None, 0, ""
            for attempt in range(1, TRANSPORT_RETRIES + 2):
                try:
                    resp = model.generate_content(
                        prompt, generation_config={"temperature": 0.95, "top_p": 0.95,
                                                   "max_output_tokens": 8192,
                                                   "response_mime_type": "application/json"},
                        request_options={"timeout": 240})
                    got = normalize_payload(json.loads(resp.text))
                    if got.get("candidates"):
                        break
                    last = "no_candidates_in_payload"
                    got = None
                except Exception as exc:  # noqa: BLE001
                    last, retries = type(exc).__name__, retries + 1
                    time.sleep(2 * attempt)
            got = got or {}
            cands = got.get("candidates", [])[:N_CANDIDATES]
            if not cands:
                rec.append({"code": code, "plan_idx": plan_idx, "arm":
                            "starved" if code in STARVED else "control",
                            "generation_failed": last, "retry_count": retries})
                path.write_text(json.dumps(rec, indent=1), encoding="utf-8")
                print(f"  {code} plan {plan_idx}: GENERATION FAILED ({last})", flush=True)
                continue
            n_leak = 0
            for i, c in enumerate(cands):
                text = str(c.get("scenario", "")).strip()
                hits = PROHIBITED.findall(text)
                leaked = bool(hits)
                n_leak += leaked
                rec.append({
                    "code": code, "plan_idx": plan_idx, "candidate_index": i + 1,
                    "arm": "starved" if code in STARVED else "control",
                    "world": w, "drive": code[0],
                    "realization_family": got.get("realization_family"),
                    "family_is_heldout": got.get("realization_family") in HELDOUT[w],
                    "text": text, "n_words": len(text.split()),
                    "leaked": leaked,
                    "leak_words": sorted({h[0].lower() for h in hits}) if hits else [],
                    "retry_count": retries,
                })
            path.write_text(json.dumps(rec, indent=1), encoding="utf-8")
            print(f"  {code} plan {plan_idx}: {n_leak}/{len(cands)} leaked  "
                  f"[{got.get('realization_family')}]", flush=True)

    # ---- R1 readout: leakage vs the frozen v2 baseline
    from collections import defaultdict
    cand = [r for r in rec if r.get("candidate_index")]
    by = defaultdict(lambda: [0, 0])
    for r in cand:
        by[r["code"]][1] += 1
        by[r["code"]][0] += r["leaked"]
    v2 = cfg["v2_baseline_leak"]
    print("\nR1 — leak rate vs v2 baseline (starved cells):")
    deltas = []
    for c in STARVED:
        n, t = by[c]
        cur = n / t if t else float("nan")
        base = v2.get(c)
        if base is not None:
            deltas.append(cur - base)
            print(f"   {c}: v2 {base:.3f} -> pilot {cur:.3f}   {cur-base:+.3f}")
        else:
            print(f"   {c}: pilot {cur:.3f}  (no v2 per-cell baseline)")
    print("\nControl cells:")
    for c in CONTROLS:
        n, t = by[c]
        print(f"   {c}: pilot {n/t if t else float('nan'):.3f}")
    overall = sum(r["leaked"] for r in cand) / max(1, len(cand))
    print(f"\n  overall pilot leak {overall:.4f}   v2 overall {v2['overall']:.4f}   "
          f"{overall - v2['overall']:+.4f}")
    print("\nR1 is the ONLY criterion this script can decide. R2-R6 require the June gate, "
          "blind judges, held-out family transfer, lexical baselines, and a second author.")
    json.dump({"per_cell": {c: {"leaked": by[c][0], "total": by[c][1]} for c in CELLS},
               "overall_leak": overall, "v2_overall": v2["overall"],
               "starved_mean_delta": sum(deltas) / len(deltas) if deltas else None,
               "decides": "R1 only"},
              open(HERE / "pilot_r1_leakage.json", "w"), indent=2, sort_keys=True)
    print("WROTE pilot_r1_leakage.json")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
