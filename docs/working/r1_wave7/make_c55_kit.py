"""Make and fill the c55 operator kit (HELM-R1 wave 7 v8, the CHAT WAVE fifth round) from the run-proven c54 scripts.
Same two token namespaces as make_c54_kit.py: {{NAME}} = operator value filled from C55_VALUES.json; __NAME__ = the worker
template's run-time token, never touched on the operator side. Unlike the c54 generator, every c54-specific literal is
derived from C54_VALUES.json (the values that were filled into the c54 scripts), so nothing is retyped by hand.

    python -X utf8 -B -I make_c55_kit.py make
    python -X utf8 -B -I make_c55_kit.py fill [--allow-missing KEY,KEY]
"""
import hashlib, json, re, sys
from pathlib import Path

C = Path(r"C:\Users\wakil\Documents\Codex")
W7 = C / "2026-10-20" / "r1_wave7"
SRC = W7 / "run_c54_r1w7v6_20261021" / "job_record"
PREV_VALUES = json.loads((W7 / "C54_VALUES.json").read_text(encoding="utf-8"))
VALUES = W7 / "C55_VALUES.json"
V8ZIP = W7 / "build_v8" / "HELM_R1_W7_20261020_SOURCE_R1W7_v8.zip"
V8FREEZE = W7 / "build_v8" / "PACKAGE_FREEZE_R1W7_v8.json"
FILES = ("aws_control_c54.py", "worker_c54.sh", "ledger_hold_c54.py", "closeout_c54.py", "independent_cleanup_c54.py", "direct_check_c54.py")
sha = lambda p: hashlib.sha256(Path(p).read_bytes()).hexdigest()
P = PREV_VALUES
PD = P["RUN_DATE"]

# every job-specific name in the c54 scripts becomes a c55 name or a {{token}} (the c54 date stays a token for c55's date)
COMPOSITE = [
    (f"helm-claude-r1w7v6-{PD}-c54", "helm-claude-r1w7v8-{{RUN_DATE}}-c55"),
    (f"helm-r1w7v6-c54-{PD}/", "helm-r1w7v8-c55-{{RUN_DATE}}/"),
    ("HELM-r1w7v6-c54", "HELM-r1w7v8-c55"),
    (f"run_c54_r1w7v6_{PD}", "run_c55_r1w7v8_{{RUN_DATE}}"),
    (f"r1w7v6_c54_reservation_{PD}", "r1w7v8_c55_reservation_{{RUN_DATE}}"),
    ("r1w7v6_c54_reservation", "r1w7v8_c55_reservation"),
    ("r1w7v6_c54_operator_notes", "r1w7v8_c55_operator_notes"),
    (f"operator-c54-{PD}", "operator-c55-{{RUN_DATE}}"),
    ("BUDGET_RESERVATION_R1W7V6_C54", "BUDGET_RESERVATION_R1W7V8_C55"),
    ("LEDGER_HOLD_RESULT_R1W7V6_C54", "LEDGER_HOLD_RESULT_R1W7V8_C55"),
    ("CLEANUP_PROOF_R1W7V6_C54", "CLEANUP_PROOF_R1W7V8_C55"),
    ("BUDGET_RECONCILIATION_ADDENDUM_CLAUDE_R1W7V6_C54_", "BUDGET_RECONCILIATION_ADDENDUM_CLAUDE_R1W7V8_C55_"),
    ("CLAUDE_R1W7V6_C54_", "CLAUDE_R1W7V8_C55_"),
    ("RETRY_DECISION_C54", "RETRY_DECISION_C55"),
    ("C54_INSTANCE_IS_LIVE", "C55_INSTANCE_IS_LIVE"),
    ("r1w7v6-c54-", "r1w7v8-c55-"),
    ("D-OP-C51-1", "D-OP-C5ONE-1"),
    (P["ZIP_NAME"], "HELM_R1_W7_20261020_SOURCE_R1W7_v8.zip"),
    ('"approval_v6"', '"approval_v8"'), ("'approval_v6'", "'approval_v8'"),
    ("x7v6_custody", "x7v8_custody"),
    ("sealed R1W7 v6 package", "sealed R1W7 v8 package"),
]
VALUE_TOKENS = [
    (f'PAYLOAD_SHA = "{P["PAYLOAD_SHA"]}"', 'PAYLOAD_SHA = "{{PAYLOAD_SHA}}"'),
    (f"RESERVATION_SHA256 = '{P['RESERVATION_SHA']}'", "RESERVATION_SHA256 = '{{RESERVATION_SHA}}'"),
    (f'APPROVAL_SHA = "{P["APPROVAL_MD_SHA"]}"', 'APPROVAL_SHA = "{{APPROVAL_MD_SHA}}"'),
    (f'FREEZE_SHA = "{P["FREEZE_SHA"]}"', 'FREEZE_SHA = "{{FREEZE_SHA}}"'),
    (P["FREEZE_SHA8"], "{{FREEZE_SHA8}}"), (P["ZIP_SHA8"], "{{ZIP_SHA8}}"), (P["CARRIER_SHA8"], "{{CARRIER_SHA8}}"),
    (P["CUSTODY_HANDOFF_NAME"], "{{CUSTODY_HANDOFF_NAME}}"),
    (P["OWNER_LINE"], "{{OWNER_LINE}}"), (P["OWNER_LINE_SHA8"], "{{OWNER_LINE_SHA8}}"), (P["OWNER_LINE_BYTES"] + " bytes", "{{OWNER_LINE_BYTES}} bytes"),
    (P["APPROVAL_JSON_SHA8"], "{{APPROVAL_JSON_SHA8}}"),
]
FORBIDDEN = ("c54", "C54", P["PAYLOAD_SHA8"], P["RESERVATION_SHA"][:8], P["APPROVAL_MD_SHA"][:8], P["FREEZE_SHA8"], P["ZIP_SHA8"],
             P["CARRIER_SHA8"], "X7_SEALED_2026", P["OWNER_LINE"], P["OWNER_LINE_SHA8"], P["APPROVAL_JSON_SHA8"], "C5ONE", "r1w7v6", "R1W7V6")
HEADER = "# Generated by make_c55_kit.py (2026-10-21) from the previous job's run-proven kit. Double-brace tokens are operator values filled by make_c55_kit.py fill; double-underscore tokens belong to the worker template and are filled only by the controller at launch.\n"


def values_skeleton():
    line = "CHAT WAVE 5 at 1 USD"
    return {"RUN_DATE": "FROM_OPERATOR_AT_LAUNCH (YYYYMMDD)",
            "ZIP_NAME": V8ZIP.name, "ZIP_PATH": str(V8ZIP), "ZIP_SHA": sha(V8ZIP), "ZIP_SHA8": sha(V8ZIP)[:8],
            "FREEZE_SHA": sha(V8FREEZE), "FREEZE_SHA8": sha(V8FREEZE)[:8],
            "OWNER_LINE": line, "OWNER_LINE_BYTES": str(len(line.encode("utf-8"))), "OWNER_LINE_SHA8": hashlib.sha256(line.encode()).hexdigest()[:8],
            "APPROVAL_MD_SHA": "FROM_APPROVAL_RECORD", "APPROVAL_JSON_SHA": "FROM_APPROVAL_RECORD", "APPROVAL_JSON_SHA8": "FROM_APPROVAL_RECORD",
            "CUSTODY_HANDOFF_NAME": "FROM_CUSTODIAN", "CUSTODY_HANDOFF_SHA": "FROM_CUSTODIAN", "CARRIER_SHA": "FROM_CUSTODIAN", "CARRIER_SHA8": "FROM_CUSTODIAN",
            "MANIFEST_SHA": "FROM_CUSTODIAN", "RECEIVER_CHECK_SHA": "FROM_CUSTODIAN", "PINS_SHA": "FROM_CUSTODIAN", "CUSTODY_DIR": "x7v8_custody",
            "PAYLOAD_SHA": "FROM_BUILD_PAYLOAD", "PAYLOAD_SHA8": "FROM_BUILD_PAYLOAD", "RESERVATION_SHA": "FROM_LEDGER_HOLD"}


def run_dir(v):
    return W7 / ("run_c55_r1w7v8_%s" % v["RUN_DATE"])


def make():
    if not VALUES.exists():
        VALUES.write_text(json.dumps(values_skeleton(), indent=1, sort_keys=True) + "\n", encoding="utf-8"); print("wrote skeleton", VALUES.name)
    v = json.loads(VALUES.read_text(encoding="utf-8"))
    assert re.fullmatch(r"\d{8}", v["RUN_DATE"]), "set RUN_DATE (YYYYMMDD) in C55_VALUES.json first"
    out = run_dir(v) / "job_record"; out.mkdir(parents=True, exist_ok=False)
    written = {}
    for name in FILES:
        t = (SRC / name).read_text(encoding="utf-8")
        t = "\n".join(l for l in t.splitlines() if not l.startswith("# Generated by make_c54_kit.py")) + "\n"
        for a, b in COMPOSITE:
            t = t.replace(a, b)
        if name.startswith("aws_control"):
            t = re.sub(r"^PAYLOAD_SHA = .*$", "PAYLOAD_SHA = '{{PAYLOAD_SHA}}'", t, count=1, flags=re.M)
        for a, b in VALUE_TOKENS:
            t = t.replace(a, b)
        t = t.replace("c54", "c55").replace("C54", "C55").replace("r1w7v6", "r1w7v8").replace("R1W7V6", "R1W7V8").replace("D-OP-C5ONE-1", "D-OP-C51-1")
        if name.endswith(".sh"):
            first, rest = t.split("\n", 1); t = first + "\n" + HEADER + rest
        else:
            t = HEADER + t
        left = [w for w in FORBIDDEN if w in t]
        assert not left, (name, left)
        if name.startswith("aws_control"):
            assert t.count("'__PAYLOAD_SHA__'") == 1 and "PAYLOAD_SHA = '{{PAYLOAD_SHA}}'" in t and "'r1w7v8_c55_reservation' in r" in t
        if name.endswith(".sh"):
            assert t.count("__PAYLOAD_SHA__") == 1 and "{{" not in t
        new = name.replace("c54", "c55")
        (out / new).write_text(t, encoding="utf-8", newline="\n")
        written[new] = {"lines": len(t.splitlines()), "fill_tokens": sorted(set(re.findall(r"\{\{([A-Z0-9_]+)\}\}", t)))}
    print(json.dumps({"run_dir": str(run_dir(v)), "written": written}, indent=1))


def fill(allow_missing):
    v = json.loads(VALUES.read_text(encoding="utf-8"))
    out = run_dir(v) / "job_record"; missing_all = {}
    for p in sorted(out.glob("*.py")):
        t = p.read_text(encoding="utf-8")
        for k, val in v.items():
            if k.startswith("_") or str(val).startswith("FROM_"):
                continue
            t = t.replace("{{%s}}" % k, str(val))
        left = sorted(set(re.findall(r"\{\{([A-Z0-9_]+)\}\}", t)))
        bad = [k for k in left if k not in allow_missing]
        assert not bad, (p.name, "unfilled tokens", bad)
        if left:
            missing_all[p.name] = left
        if p.name.startswith("aws_control"):
            assert t.count("'__PAYLOAD_SHA__'") == 1, "controller template site damaged"
        p.write_text(t, encoding="utf-8", newline="\n")
    w = (out / "worker_c55.sh").read_text(encoding="utf-8"); assert w.count("__PAYLOAD_SHA__") == 1 and "{{" not in w
    print(json.dumps({"filled_from": str(VALUES), "still_missing_by_file": missing_all, "template_sites_intact": True}, indent=1))


if __name__ == "__main__":
    cmd = sys.argv[1] if len(sys.argv) > 1 else "make"
    if cmd == "make":
        make()
    elif cmd == "fill":
        allow = set(sys.argv[sys.argv.index("--allow-missing") + 1].split(",")) if "--allow-missing" in sys.argv else set()
        fill(allow)
    else:
        raise SystemExit("usage: make | fill [--allow-missing KEY,KEY]")
