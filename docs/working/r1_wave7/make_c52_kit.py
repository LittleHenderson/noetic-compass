def run_dir(v):
    return W7 / ("run_c52_r1w7v4_%s" % v["RUN_DATE"])


def make():
    if not VALUES.exists():
        VALUES.write_text(json.dumps(values_skeleton(), indent=1, sort_keys=True) + "\n", encoding="utf-8")
        print("wrote skeleton", VALUES.name)
    v = json.loads(VALUES.read_text(encoding="utf-8"))
    assert re.fullmatch(r"\d{8}", v["RUN_DATE"]), "set RUN_DATE (YYYYMMDD) in C52_VALUES.json first"
    out = run_dir(v) / "job_record"
    out.mkdir(parents=True, exist_ok=False)
    written = {}
    for name in FILES:
        t = (SRC / name).read_text(encoding="utf-8")
        for a, b in COMPOSITE:
            t = t.replace(a, b)
        t = re.sub(r"^PAYLOAD_SHA = .*$", "PAYLOAD_SHA = '{{PAYLOAD_SHA}}'", t, count=1, flags=re.M) if name.startswith("aws_control") else t
        for a, b in VALUE_TOKENS:
            t = t.replace(a, b)
        t = t.replace("c51", "c52").replace("C51", "C52").replace("D-OP-C5ONE-1", "D-OP-C51-1")
        if name.endswith(".sh"):
            first, rest = t.split("\n", 1); t = first + "\n" + HEADER + rest
        else:
            t = HEADER + t
        left = [w for w in FORBIDDEN if w in t and not (w == "c51" and t.count(w) == t.count("D-OP-C51-1"))]
        assert not left, (name, left)
        if name.startswith("aws_control"):
            assert t.count("'__PAYLOAD_SHA__'") == 1 and "PAYLOAD_SHA = '{{PAYLOAD_SHA}}'" in t, "controller template site or fill target wrong"
        if name.endswith(".sh"):
            assert t.count("__PAYLOAD_SHA__") == 1 and "{{" not in t, "worker template must keep its run-time tokens and carry no fill token"
        new = name.replace("c51", "c52")
        (out / new).write_text(t, encoding="utf-8", newline="\n")
        written[new] = {"lines": len(t.splitlines()), "fill_tokens": sorted(set(re.findall(r"\{\{([A-Z0-9_]+)\}\}", t)))}
    print(json.dumps({"run_dir": str(run_dir(v)), "written": written}, indent=1))


def fill(allow_missing):
    v = json.loads(VALUES.read_text(encoding="utf-8"))
    out = run_dir(v) / "job_record"
    missing_all = {}
    for p in sorted(out.glob("*.py")):
        t = p.read_text(encoding="utf-8")
        for k, val in v.items():
            if k.startswith("_") or str(val).startswith("FROM_"):
                continue
            t = t.replace("{{%s}}" % k, str(val))
        left = sorted(set(re.findall(r"\{\{([A-Z0-9_]+)\}\}", t)))
        bad = [k for k in left if k not in allow_missing]
        assert not bad, (p.name, "unfilled tokens", bad)
        if left:
            missing_all[p.name] = left
        if p.name.startswith("aws_control"):
            assert t.count("'__PAYLOAD_SHA__'") == 1, "controller template site damaged"
        p.write_text(t, encoding="utf-8", newline="\n")
    w = (out / "worker_c52.sh").read_text(encoding="utf-8")
    assert w.count("__PAYLOAD_SHA__") == 1 and "{{" not in w
    print(json.dumps({"filled_from": str(VALUES), "still_missing_by_file": missing_all, "template_sites_intact": True}, indent=1))


if __name__ == "__main__":
    cmd = sys.argv[1] if len(sys.argv) > 1 else "make"
    if cmd == "make":
        make()
    elif cmd == "fill":
        allow = set()
        if "--allow-missing" in sys.argv:
            allow = set(sys.argv[sys.argv.index("--allow-missing") + 1].split(","))
        fill(allow)
    else:
        raise SystemExit("usage: make | fill [--allow-missing KEY,KEY]")
